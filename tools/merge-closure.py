"""Сведение разбора «чем закрывается тема» (этап РАЗБОР-3).

Сверка сказала, что набор обязан покрыть. Этот этап отвечает, **чем** каждая
единица закрывается: правилом, справочником, штатным механизмом платформы
или своим скриптом.

Порядок способов не случаен и проверяется здесь же. Решение 18 владельца:
не переизобретать то, что уже умеет платформа или инструменты вокруг неё;
свой скрипт заводится только при реальной практической причине, несущей
не поддельную пользу. Поэтому чем дороже способ, тем строже требование
к обоснованию — и строже всего к генератору, который ошибается в сторону
испорченной конфигурации.

Отдельно сводится пометка `бд`: по решению 19 всё, что касается баз данных,
после сборки плагина пойдёт на критический пересмотр, и этот свод даёт ему
готовый список вместо задачи перечитывать всё заново.

Запуск: PYTHONIOENCODING=utf-8 python tools/merge-closure.py <каталог с out-*.json>
"""
import argparse
import importlib.util
import json
import os
import sys
from pathlib import Path

# Вывод этих скриптов — кириллица и знаки «», «—», «→». Пока stdout остаётся
# окном консоли, беды нет: Python 3.14 на Windows пишет туда через WriteConsoleW
# и отдаёт utf-8 при любой кодовой странице — проверено запуском 25.08.2026 под
# chcp 866, 1251 и 65001, во всех трёх sys.stdout.encoding == 'utf-8'.
#
# Ломается ПЕРЕНАПРАВЛЕНИЕ: когда вывод уходит в файл или в трубу, Python берёт
# ANSI-кодировку системы (здесь cp1251), и первый же знак вне неё роняет скрипт
# трассировкой вместо отчёта. Так падал check-1c-cli.py, отгружаемый внутри
# навыка, и так its-search.py не мог отдать даже --help.
#
# Две оговорки, каждая из-за собственной ошибки первой редакции:
#   errors= передаём прежний — reconfigure(encoding=...) молча ставит strict,
#   а интерпретатор держит на stdout surrogateescape и на stderr
#   backslashreplace нарочно, чтобы печать имени файла с одиночным суррогатом
#   (обычное дело в Windows) не роняла сам вывод;
#   при заданной PYTHONIOENCODING не трогаем ничего — иначе у человека
#   не остаётся способа задать кодировку под своего потребителя вывода.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass


ROOT = Path(__file__).resolve().parent.parent

_spec = importlib.util.spec_from_file_location(
    "merge_reference_reading", ROOT / "tools" / "merge-reference-reading.py")
_mrr = importlib.util.module_from_spec(_spec)
sys.modules["merge_reference_reading"] = _mrr
_spec.loader.exec_module(_mrr)
SECTIONS = _mrr.SECTIONS

СПОСОБЫ = ["правило", "справочник", "штатный механизм", "скрипт"]
КЛАССЫ = ["обёртка", "проверяльщик", "генератор"]
ОБЪЁМЫ = ["строка", "абзац", "раздел", "отдельный файл"]

# Чем дороже способ, тем длиннее требуется обоснование. Это не придирка
# к многословию: короткое «нужен скрипт» невозможно оспорить, а значит
# невозможно и проверить. Пороги подобраны по живым выводам — правило
# объясняется одной фразой, генератор одной фразой объяснить нельзя.
ПОРОГ = {"правило": 0, "справочник": 40, "штатный механизм": 40, "скрипт": 80}
ПОРОГ_ГЕНЕРАТОРА = 160


def fail(message, code=2):
    sys.stdout.write(message + "\n")
    raise SystemExit(code)


def проверить(data, ожидаемые):
    out = []
    раздел = data.get("раздел", "")
    if раздел not in SECTIONS:
        out.append("раздел «%s» не из пятнадцати" % раздел)

    единицы = data.get("единицы")
    if not isinstance(единицы, list):
        return out + ["ожидался список «единицы»"]

    seen = set()
    for u in единицы:
        имя = str(u.get("что", "")).strip()
        if not имя:
            out.append("запись без имени")
            continue
        if имя in seen:
            out.append("единица «%s» разобрана дважды" % имя)
        seen.add(имя)

        способ = str(u.get("чем_закрывается", "")).strip()
        if способ not in СПОСОБЫ:
            out.append("«%s»: способ «%s» не из перечня: %s"
                       % (имя, способ, ", ".join(СПОСОБЫ)))
            continue

        почему = str(u.get("почему", "")).strip()
        класс = str(u.get("класс_скрипта", "")).strip()
        механизм = str(u.get("механизм", "")).strip()

        порог = ПОРОГ[способ]
        if способ == "скрипт" and класс == "генератор":
            порог = ПОРОГ_ГЕНЕРАТОРА
        if len(почему) < порог:
            out.append("«%s»: способ «%s»%s требует обоснования не короче %d знаков, "
                       "дано %d. Чем дороже способ, тем строже: короткое «нужен скрипт» "
                       "нельзя оспорить, а значит нельзя и проверить"
                       % (имя, способ, (" класса «%s»" % класс) if класс else "",
                          порог, len(почему)))

        if способ == "скрипт":
            if класс not in КЛАССЫ:
                out.append("«%s»: класс скрипта «%s» не из перечня: %s"
                           % (имя, класс, ", ".join(КЛАССЫ)))
        elif класс:
            out.append("«%s»: класс скрипта заполнен, хотя способ «%s»" % (имя, способ))

        if способ == "штатный механизм":
            if not механизм:
                out.append("«%s»: сказано «штатный механизм», но он не назван — "
                           "механизм без имени и места описания проверить нельзя" % имя)
        elif механизм:
            out.append("«%s»: механизм заполнен, хотя способ «%s»" % (имя, способ))

        объём = str(u.get("объём", "")).strip()
        if объём not in ОБЪЁМЫ:
            out.append("«%s»: объём «%s» не из перечня: %s"
                       % (имя, объём, ", ".join(ОБЪЁМЫ)))

        if not isinstance(u.get("бд"), bool):
            out.append("«%s»: поле «бд» должно быть true или false — "
                       "по решению 19 это список для отдельного этапа" % имя)

    не_разобраны = sorted(set(ожидаемые) - seen)
    лишние = sorted(seen - set(ожидаемые))
    if не_разобраны:
        out.append("не разобраны %d единиц: %s"
                   % (len(не_разобраны), ", ".join(не_разобраны[:6])))
    if лишние:
        out.append("разобраны единицы не из этого раздела: %s" % ", ".join(лишние[:6]))
    return out


def merge(каталог):
    каталог = Path(каталог)
    входы = {}
    for p in sorted(каталог.glob("*.json")):
        if p.name.startswith("out-") or not p.stem.startswith("1c-"):
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        if "единицы" in d:
            входы[p.stem] = [u["что"] for u in d["единицы"]]
    if not входы:
        fail("[ошибка] в %s нет входных файлов разделов." % каталог)

    выходы = sorted(каталог.glob("out-*.json"))
    if not выходы:
        fail("[ошибка] в %s нет ни одного файла out-*.json.\n"
             "Разбор ведут агенты; без их выводов сводить нечего.\n"
             "Пустой файл не записан намеренно." % каталог)

    разделы, problems, covered = [], [], set()
    for p in выходы:
        stem = p.stem[4:]
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except ValueError as e:
            problems.append("%s: не разбирается как JSON: %s" % (p.name, e))
            continue
        ожид = входы.get(stem)
        if ожид is None:
            problems.append("%s: нет входного файла %s.json" % (p.name, stem))
            ожид = []
        covered.add(stem)
        for n in проверить(d, ожид):
            problems.append("%s: %s" % (p.name, n))
        разделы.append(d)

    for stem in sorted(set(входы) - covered):
        problems.append("раздел %s не разобран — нет out-%s.json" % (stem, stem))

    свод = {s: 0 for s in СПОСОБЫ}
    классы = {k: 0 for k in КЛАССЫ}
    бд = 0
    всего = 0
    for d in разделы:
        for u in d.get("единицы") or []:
            всего += 1
            if u.get("чем_закрывается") in свод:
                свод[u["чем_закрывается"]] += 1
            if u.get("класс_скрипта") in классы:
                классы[u["класс_скрипта"]] += 1
            if u.get("бд") is True:
                бд += 1
    разделы.sort(key=lambda d: -len(d.get("единицы") or []))

    return {
        "что_это": "Чем закрывается каждая тема набора: правилом, справочником, "
                   "штатным механизмом платформы или своим скриптом.",
        "разделов": len(разделы),
        "разделов_ожидалось": len(входы),
        "не_разобраны": sorted(set(входы) - covered),
        "единиц": всего,
        "по_способам": свод,
        "скрипты_по_классам": {k: v for k, v in классы.items() if v},
        "под_решением_19": бд,
        "разделы": разделы,
    }, problems


def as_markdown(c):
    L = []
    a = L.append
    a("# Чем закрывается каждая тема (РАЗБОР-3)")
    a("")
    a("Порождается `tools/merge-closure.py`.")
    a("")
    if c.get("не_разобраны"):
        a("> **Свод неполон.** Разобрано %d разделов из %d. Не разобраны: %s."
          % (c["разделов"], c["разделов_ожидалось"],
             ", ".join("`%s`" % x for x in c["не_разобраны"])))
        a("")
    a("Единиц всего: **%d**." % c["единиц"])
    a("")
    a("| Чем закрывается | Единиц |")
    a("|---|---|")
    for k in СПОСОБЫ:
        a("| %s | %d |" % (k, c["по_способам"].get(k, 0)))
    a("")
    if c["скрипты_по_классам"]:
        a("Скрипты по классам: "
          + ", ".join("%s — %d" % (k, v) for k, v in c["скрипты_по_классам"].items()) + ".")
        a("")
    a("Под решением 19 (работа с базой, критический пересмотр после сборки): "
      "**%d** единиц." % c["под_решением_19"])
    a("")
    a("Порядок способов задан решением 18 и не переставляется: платформа →")
    a("инструменты вокруг неё → правило → справочник → и лишь затем свой скрипт.")
    a("Не переизобретать то, что уже умеет платформа: свой скрипт заводится только")
    a("при реальной практической причине, несущей не поддельную пользу.")
    a("")
    for d in c["разделы"]:
        единицы = d.get("единицы") or []
        a("## %s — %d" % (d.get("раздел", "?"), len(единицы)))
        a("")
        a("| Что | Чем закрывается | Объём | БД |")
        a("|---|---|---|---|")
        for u in единицы:
            способ = u.get("чем_закрывается", "")
            if u.get("класс_скрипта"):
                способ += " (%s)" % u["класс_скрипта"]
            if u.get("механизм"):
                способ += " — %s" % str(u["механизм"])[:60]
            a("| %s | %s | %s | %s |"
              % (str(u.get("что", "")).replace("|", "\\|"), способ,
                 u.get("объём", ""), "да" if u.get("бд") else ""))
        a("")
        for z in (d.get("замечания") or []):
            a("> %s" % z)
            a("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("каталог")
    ap.add_argument("--out-json", default=str(ROOT / "docs" / "closure.json"))
    ap.add_argument("--out-md", default=str(ROOT / "docs" / "closure.md"))
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    c, problems = merge(args.каталог)
    for p in problems:
        print("[замечание] %s" % p)
    if problems and not args.force:
        print("\nзамечаний: %d. Файл не записан." % len(problems))
        raise SystemExit(1)

    Path(args.out_json).write_text(json.dumps(c, ensure_ascii=False, indent=2) + "\n",
                                   encoding="utf-8", newline="\n")
    Path(args.out_md).write_text(as_markdown(c), encoding="utf-8", newline="\n")
    print("разделов: %d | единиц: %d | под решением 19: %d | замечаний: %d"
          % (c["разделов"], c["единиц"], c["под_решением_19"], len(problems)))
    for k in СПОСОБЫ:
        print("  %-18s %3d" % (k, c["по_способам"].get(k, 0)))
    if c["скрипты_по_классам"]:
        for k, v in c["скрипты_по_классам"].items():
            print("    из них %-14s %3d" % (k, v))
    print("записано: %s, %s" % (args.out_json, args.out_md))


if __name__ == "__main__":
    main()
