#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Разрешает навыки набора поимённо в списке разрешений Kilo.

Зачем. В `~/.config/kilo/kilo.jsonc` блок "skill" по умолчанию содержит
`"*": "ask"`. В режиме `--auto` навык, не разрешённый поимённо, до вызова
не доходит и молчит — прогон выглядит как «навык не выбрался». Это уже
дало четыре ложных отказа подряд: под них попали прогоны Kilo по
`1c-queries`, `1c-security`, `1c-managed-forms` и `1c-access-rights`.
Разбор — в комментарии `tools/run-prompt.ps1`.

Почему правка текстовая, а не через json.load. Файл — JSONC: в нём есть
комментарии и, возможно, висячие запятые. Разобрать его как JSON и записать
обратно значит стереть комментарии владельца. Поэтому правка хирургическая:
в блок "skill" дописываются недостающие строки, остальное не трогается
ни на байт.

Чужой инструмент не судим (правило 11 набора): если конфига нет, если в нём
нет блока "skill" или блок не разбирается — это предупреждение и код возврата
0, а не отказ. Отказ только на том, что мы испортили сами.

Использование:
    python tools/allow-skills-in-kilo.py --каталог skills
    python tools/allow-skills-in-kilo.py --каталог skills --проверить
"""
import argparse
import os
import re
import shutil
import sys

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОНФИГ_ПО_УМОЛЧАНИЮ = os.path.join("~", ".config", "kilo", "kilo.jsonc")

# Ключ блока разрешений навыков. Ищем именно `"skill"` с двоеточием и `{`,
# чтобы не поймать одноимённое слово в комментарии или в другом блоке.
БЛОК = re.compile(r'"skill"\s*:\s*\{')


def имена_навыков(каталог):
    """Имена подкаталогов каталога навыков — они же имена навыков."""
    if not os.path.isdir(каталог):
        return []
    return sorted(
        и for и in os.listdir(каталог)
        if os.path.isdir(os.path.join(каталог, и))
        and os.path.isfile(os.path.join(каталог, и, "SKILL.md"))
    )


def границы_блока(текст):
    """Возвращает (начало_тела, конец_тела) блока "skill" или None.

    Начало — сразу после открывающей `{`, конец — позиция закрывающей `}`.
    Скобки считаем сами: внутри блока могут быть вложенные объекты.
    """
    м = БЛОК.search(текст)
    if not м:
        return None
    i = м.end()
    глубина = 1
    в_строке = False
    экран = False
    while i < len(текст):
        c = текст[i]
        if в_строке:
            if экран:
                экран = False
            elif c == "\\":
                экран = True
            elif c == '"':
                в_строке = False
        elif c == '"':
            в_строке = True
        elif c == "{":
            глубина += 1
        elif c == "}":
            глубина -= 1
            if глубина == 0:
                return (м.end(), i)
        i += 1
    return None


def уже_разрешены(тело):
    """Имена ключей, уже присутствующих в теле блока."""
    return set(re.findall(r'"([^"]+)"\s*:', тело))


def отступ(тело):
    """Отступ существующих строк блока; шесть пробелов, если строк нет."""
    м = re.search(r'\n([ \t]+)"', тело)
    return м.group(1) if м else "      "


def врезать(текст, границы, имена):
    """Дописывает недостающие имена в блок, не трогая остальное.

    Вставляем после первой строки тела — порядок ключей в объекте JSON
    значения не имеет, а так правка видна сразу и не ломает инвариант
    «у последней записи нет запятой».
    """
    начало, конец = границы
    тело = текст[начало:конец]
    отст = отступ(тело)
    строки = ["%s%s: %s" % (отст, '"%s"' % и, '"allow"') for и in имена]

    если_пусто = не_пустое(тело) is False
    if если_пусто:
        новое = "\n" + ",\n".join(строки) + "\n" + отст[:-2]
        return текст[:начало] + новое + текст[конец:]

    # Тело непустое: вставляем перед первой существующей записью,
    # каждую строку с запятой — инвариант последней записи не задет.
    м = re.search(r'\n[ \t]*"', тело)
    точка = начало + (м.start() if м else 0)
    вставка = "".join("\n" + с + "," for с in строки)
    return текст[:точка] + вставка + текст[точка:]


def не_пустое(тело):
    """Есть ли в теле блока хоть одна запись."""
    без_комментариев = re.sub(r"//[^\n]*", "", тело)
    без_комментариев = re.sub(r"/\*.*?\*/", "", без_комментариев, flags=re.S)
    return bool(без_комментариев.strip())


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--каталог", required=True,
                   help="каталог навыков набора (подкаталоги с SKILL.md)")
    р.add_argument("--конфиг", default=КОНФИГ_ПО_УМОЛЧАНИЮ,
                   help="путь к kilo.jsonc")
    р.add_argument("--проверить", action="store_true",
                   help="ничего не писать, только сказать, что изменилось бы")
    а = р.parse_args()

    навыки = имена_навыков(а.каталог)
    if not навыки:
        print("[предупреждение] в %s нет навыков — нечего разрешать" % а.каталог)
        return 0

    конфиг = os.path.expanduser(а.конфиг)
    if not os.path.isfile(конфиг):
        print("[предупреждение] %s не найден — список разрешений Kilo не тронут" % конфиг)
        return 0

    текст = open(конфиг, encoding="utf-8").read()
    границы = границы_блока(текст)
    if границы is None:
        print("[предупреждение] в %s нет разбираемого блока \"skill\" — "
              "правка не выполнена" % конфиг)
        return 0

    тело = текст[границы[0]:границы[1]]
    есть = уже_разрешены(тело)
    нужны = [и for и in навыки if и not in есть]

    if not нужны:
        print("список разрешений Kilo: все %d навыков уже разрешены" % len(навыки))
        return 0

    if а.проверить:
        print("добавили бы в %s: %s" % (конфиг, ", ".join(нужны)))
        return 0

    новый = врезать(текст, границы, нужны)

    # Проверяем себя: блок должен остаться разбираемым, а имена — появиться.
    свои = границы_блока(новый)
    if свои is None:
        print("[отказ] после правки блок \"skill\" перестал разбираться — "
              "файл не тронут", file=sys.stderr)
        return 1
    появились = уже_разрешены(новый[свои[0]:свои[1]])
    пропали = [и for и in нужны if и not in появились]
    if пропали:
        print("[отказ] после правки не хватает имён: %s — файл не тронут"
              % ", ".join(пропали), file=sys.stderr)
        return 1

    запас = конфиг + ".bak"
    shutil.copy2(конфиг, запас)
    with open(конфиг, "w", encoding="utf-8", newline="") as f:
        f.write(новый)
    print("список разрешений Kilo: добавлено %d — %s (запасная копия: %s)"
          % (len(нужны), ", ".join(нужны), os.path.basename(запас)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
