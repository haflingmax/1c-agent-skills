#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Разрешает навыки набора поимённо в списке разрешений Kilo.

Зачем. В `~/.config/kilo/kilo.jsonc` блок "skill" по умолчанию содержит
`"*": "ask"`. В режиме `--auto` навык, не разрешённый поимённо, до вызова
не доходит и молчит — прогон выглядит как «навык не выбрался». Это уже
дало четыре ложных отказа подряд: под них попали прогоны Kilo по
`1c-queries`, `1c-security`, `1c-managed-forms` и `1c-access-rights`.
Разбор — в комментарии `tools/run-prompt.ps1`.

Порядок записей в блоке решает. Это не общий JSON, а формат правил Kilo:
блок "skill" — СПИСОК правил сверху вниз, и движок берёт ПОСЛЕДНЕЕ
совпавшее (`findLast` по всем записям, включая "*", которая совпадает
с любым именем). Поэтому запись `"имя-навыка": "allow"`, стоящая ВЫШЕ
`"*": "ask"`, ничего не разрешает: звёздочка ниже неё перебивает её своим
"ask". Разрешение действует, только если стоит НИЖЕ звёздочки. Отсюда и
хирургическая правка: недостающие и смещённые выше звезды имена нужно
дописывать (или переставлять) СРАЗУ ПОД строкой `"*"`, а не куда попало.

Почему правка текстовая, а не через json.load. Файл — JSONC: в нём есть
комментарии и, возможно, висячие запятые. Разобрать его как JSON и записать
обратно значит стереть комментарии владельца. Поэтому правка хирургическая:
в блок "skill" дописываются недостающие строки и переставляются смещённые,
остальное не трогается ни на байт.

Чужой инструмент не судим (правило 11 набора): если конфига нет, если в нём
нет блока "skill" или блок не разбирается — это предупреждение и код возврата
0, а не отказ. Отказ только на том, что мы испортили сами.

Использование:
    python tools/allow-skills-in-kilo.py --каталог skills
    python tools/allow-skills-in-kilo.py --каталог skills --проверить
"""
import argparse
import os
import re
import shutil
import sys

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОНФИГ_ПО_УМОЛЧАНИЮ = os.path.join("~", ".config", "kilo", "kilo.jsonc")

# Ключ блока разрешений навыков. Ищем именно `"skill"` с двоеточием и `{`,
# чтобы не поймать одноимённое слово в комментарии или в другом блоке.
БЛОК = re.compile(r'"skill"\s*:\s*\{')

# Одна запись блока: "имя": "значение" на своей строке, с необязательными
# отступом, висячей запятой и хвостовым `//`-комментарием. Строка коммента
# (`// "имя": "значение"`) этим не ловится — она не начинается с кавычки
# сразу после отступа, а с `//`, так что закомментированные записи не
# принимаются за настоящие и не участвуют в перестановке.
ЗАПИСЬ = re.compile(
    r'^(?P<indent>[ \t]*)"(?P<key>[^"]+)"[ \t]*:[ \t]*"(?P<value>[^"]*)"'
    r'(?P<comma>[ \t]*,)?[ \t]*(?P<comment>//[^\n]*)?[ \t]*$',
    re.M,
)


def имена_навыков(каталог):
    """Имена подкаталогов каталога навыков — они же имена навыков."""
    if not os.path.isdir(каталог):
        return []
    return sorted(
        и for и in os.listdir(каталог)
        if os.path.isdir(os.path.join(каталог, и))
        and os.path.isfile(os.path.join(каталог, и, "SKILL.md"))
    )


def границы_блока(текст):
    """Возвращает (начало_тела, конец_тела) блока "skill" или None.

    Начало — сразу после открывающей `{`, конец — позиция закрывающей `}`.
    Скобки считаем сами: внутри блока могут быть вложенные объекты.
    """
    м = БЛОК.search(текст)
    if not м:
        return None
    i = м.end()
    глубина = 1
    в_строке = False
    экран = False
    while i < len(текст):
        c = текст[i]
        if в_строке:
            if экран:
                экран = False
            elif c == "\\":
                экран = True
            elif c == '"':
                в_строке = False
        elif c == '"':
            в_строке = True
        elif c == "{":
            глубина += 1
        elif c == "}":
            глубина -= 1
            if глубина == 0:
                return (м.end(), i)
        i += 1
    return None


def отступ(тело):
    """Отступ существующих строк блока; шесть пробелов, если строк нет."""
    м = re.search(r'\n([ \t]+)"', тело)
    return м.group(1) if м else "      "


def не_пустое(тело):
    """Есть ли в теле блока хоть одна запись."""
    без_комментариев = re.sub(r"//[^\n]*", "", тело)
    без_комментариев = re.sub(r"/\*.*?\*/", "", без_комментариев, flags=re.S)
    return bool(без_комментариев.strip())


def оценить(тело, навыки):
    """Делит переданные имена навыков на три кучки по факту в теле блока.

    - отсутствуют: имени нет вовсе;
    - смещены: имя есть, но ВСЕ его вхождения выше "*" — для Kilo (см.
      объяснение в шапке файла про findLast) это равносильно отсутствию,
      звёздочка своим "ask" их перебивает;
    - остальные (не возвращаются) — имя действует, есть вхождение ниже
      звезды или звезды в блоке вовсе нет (тогда позиция не важна, это
      старое, дозвёздное поведение списка разрешений).

    Возвращает (звезда, отсутствуют, смещены), где звезда — либо re.Match
    записи "*", либо None, если её в блоке нет.
    """
    записи = list(ЗАПИСЬ.finditer(тело))
    звезда = next((з for з in записи if з.group("key") == "*"), None)

    отсутствуют, смещены = [], []
    for и in навыки:
        вхождения = [з for з in записи if з.group("key") == и]
        if not вхождения:
            отсутствуют.append(и)
        elif звезда is not None and all(з.start() < звезда.start() for з in вхождения):
            смещены.append(и)
    return звезда, отсутствуют, смещены


def строка_с_переводом(запись, тело):
    """Границы всей строки записи в `тело`, включая её перевод строки.

    Нужно, чтобы при удалении смещённой записи не оставлять пустую строку:
    убираем не только совпадение регулярки, но и `\\n` (или `\\r\\n`) следом.
    """
    начало, конец = запись.start(), запись.end()
    if тело[конец:конец + 2] == "\r\n":
        конец += 2
    elif тело[конец:конец + 1] == "\n":
        конец += 1
    return начало, конец


def врезать(текст, границы, отсутствуют, смещены):
    """Дописывает недостающие имена и переставляет смещённые под "*".

    Куда именно вставлять — решает наличие звёздочки:

    - звёздочки нет вовсе: перебивать нечему, любое место в блоке одинаково
      действует. Оставляем прежнее поведение — перед первой записью.
    - звёздочка есть: единственное место, откуда разрешение НАВЕРНЯКА
      действует — сразу под её строкой. Поэтому: (1) вхождения смещённых
      имён выше звезды вычищаются целыми строками (без осиротевшей пустой
      строки на их месте), а (2) все нужные имена — и отсутствовавшие,
      и снятые сверху — дописываются одним блоком сразу после строки "*".
      Если у звезды не было запятой (она была последней записью), запятая
      добавляется — иначе следом за ней будет невалидный JSON.
    """
    начало, конец = границы
    тело = текст[начало:конец]
    отст = отступ(тело)
    нужны = отсутствуют + смещены

    if не_пустое(тело) is False:
        новое = ("\n" + ",\n".join('%s"%s": "allow"' % (отст, и) for и in нужны)
                 + "\n" + отст[:-2])
        return текст[:начало] + новое + текст[конец:]

    записи = list(ЗАПИСЬ.finditer(тело))
    звезда = next((з for з in записи if з.group("key") == "*"), None)

    if звезда is None:
        # Прежнее поведение: перебивать нечему, вставляем перед первой
        # существующей записью, каждую строку с запятой — инвариант
        # «у последней записи нет запятой» этим не задет.
        м = re.search(r'\n[ \t]*"', тело)
        точка = м.start() if м else 0
        строки = ['%s"%s": "allow"' % (отст, и) for и in нужны]
        вставка = "".join("\n" + с + "," for с in строки)
        новое_тело = тело[:точка] + вставка + тело[точка:]
        return текст[:начало] + новое_тело + текст[конец:]

    # --- звёздочка есть: сперва убираем смещённые записи выше неё ---
    делеты = sorted(
        (строка_с_переводом(з, тело)
         for и in смещены for з in записи
         if з.group("key") == и and з.start() < звезда.start()),
        key=lambda с: с[0],
    )
    части, предыдущий = [], 0
    for нач, кон in делеты:
        части.append(тело[предыдущий:нач])
        предыдущий = кон
    части.append(тело[предыдущий:])
    тело2 = "".join(части)

    # Удаление сдвинуло все позиции после него — звезду и остальные записи
    # ищем заново в укороченном теле, а не пересчитываем смещения вручную.
    записи2 = list(ЗАПИСЬ.finditer(тело2))
    звезда2 = next(з for з in записи2 if з.group("key") == "*")
    есть_ниже = any(з.start() > звезда2.end() for з in записи2 if з is not звезда2)

    if звезда2.group("comma") is None:
        # Звезда была последней записью — без запятой следом за нашей
        # вставкой получится невалидный JSON, чиним это первым делом.
        место = звезда2.end("value") + 1
        тело2 = тело2[:место] + "," + тело2[место:]

    точка = тело2.index("\n", звезда2.start()) + 1
    строки = ['%s"%s": "allow"' % (отст, и) for и in нужны]
    if есть_ниже:
        # После вставки всё равно что-то следует - у каждой новой строки
        # своя запятая, инвариант последней записи блока не про них.
        вставка = "".join(с + ",\n" for с in строки)
    else:
        # Наши строки становятся новым хвостом блока - запятой лишена
        # только последняя из них.
        вставка = "".join(с + ",\n" for с in строки[:-1]) + строки[-1] + "\n"
    тело2 = тело2[:точка] + вставка + тело2[точка:]
    return текст[:начало] + тело2 + текст[конец:]


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--каталог", required=True,
                   help="каталог навыков набора (подкаталоги с SKILL.md)")
    р.add_argument("--конфиг", default=КОНФИГ_ПО_УМОЛЧАНИЮ,
                   help="путь к kilo.jsonc")
    р.add_argument("--проверить", action="store_true",
                   help="ничего не писать, только сказать, что изменилось бы")
    а = р.parse_args()

    навыки = имена_навыков(а.каталог)
    if not навыки:
        print("[предупреждение] в %s нет навыков — нечего разрешать" % а.каталог)
        return 0

    конфиг = os.path.expanduser(а.конфиг)
    if not os.path.isfile(конфиг):
        print("[предупреждение] %s не найден — список разрешений Kilo не тронут" % конфиг)
        return 0

    текст = open(конфиг, encoding="utf-8").read()
    границы = границы_блока(текст)
    if границы is None:
        print("[предупреждение] в %s нет разбираемого блока \"skill\" — "
              "правка не выполнена" % конфиг)
        return 0

    тело = текст[границы[0]:границы[1]]
    _, отсутствуют, смещены = оценить(тело, навыки)
    нужны = отсутствуют + смещены

    if not нужны:
        print("список разрешений Kilo: все %d навыков уже разрешены" % len(навыки))
        return 0

    if а.проверить:
        части = []
        if отсутствуют:
            части.append("добавить: %s" % ", ".join(отсутствуют))
        if смещены:
            части.append('переставить ниже "*" (сейчас выше — не действуют '
                          'из-за findLast): %s' % ", ".join(смещены))
        print("список разрешений Kilo, %s: %s" % (конфиг, "; ".join(части)))
        return 0

    новый = врезать(текст, границы, отсутствуют, смещены)

    # Проверяем себя той же меркой, что и вставку: имена должны не только
    # присутствовать, но и стоять ниже "*" — иначе правка ничего не решает,
    # а инструмент как раз это и обязан заметить, а не бодро отчитаться.
    свои = границы_блока(новый)
    if свои is None:
        print("[отказ] после правки блок \"skill\" перестал разбираться — "
              "файл не тронут", file=sys.stderr)
        return 1
    _, отсутствуют_после, смещены_после = оценить(новый[свои[0]:свои[1]], нужны)
    если_плохо = отсутствуют_после + смещены_после
    if если_плохо:
        print("[отказ] после правки не разрешены по-настоящему: %s — файл не тронут"
              % ", ".join(если_плохо), file=sys.stderr)
        return 1

    запас = конфиг + ".bak"
    shutil.copy2(конфиг, запас)
    with open(конфиг, "w", encoding="utf-8", newline="") as f:
        f.write(новый)

    части = []
    if отсутствуют:
        части.append("добавлено %d (%s)" % (len(отсутствуют), ", ".join(отсутствуют)))
    if смещены:
        части.append('переставлено ниже "*" %d (%s)' % (len(смещены), ", ".join(смещены)))
    print("список разрешений Kilo: %s (запасная копия: %s)"
          % ("; ".join(части), os.path.basename(запас)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
