      # в progress.jsonl, который агенту недоступен.
      # Ещё один уровень («w») намеренно: родитель рабочего каталога
      # оказывается пустым, и осмотр «что рядом» не даёт вообще ничего.
      $runDir = Join-Path (Join-Path ([System.IO.Path]::GetTempPath()) (
        "case-" + [guid]::NewGuid().ToString("N").Substring(0, 12))) "w"
      Write-Line @{
        event = 'run-start'; env = $envName; pair = $pair.Id; pol = $pol
        prompt = $prompt; time = (Get-Date).ToString('o')
