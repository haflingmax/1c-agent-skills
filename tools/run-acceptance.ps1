      # kilo-p13-Neg… указывает на отрицательный сценарий: ожидаемое
      # поведение — зафиксировать отсутствие исходников». То есть тест
      # сообщал агенту, что от него ждут отказа, — а именно отказ и есть
      # мера половины пар.
      #
      # Поэтому имя каталога — случайное, и лежит он не рядом с другими
      # прогонами, а отдельной веткой в TEMP: подняться к соседям оттуда
