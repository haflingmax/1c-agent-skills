"""Перепись всех утверждений об отсутствии: где набор говорит «этого нет».

Самый дорогой класс ошибок этого набора — **ложное отрицание**: навык пишет
«источник об этом не говорит», а источник говорит. Впервые пойман
в `1c-integrations` (26.08), в `1c-publish-and-operate` дал шесть грубых
находок из восемнадцати — больше, чем любой другой класс.

    python tools/check-negations.py --навык 1c-publish-and-operate
    python tools/check-negations.py --все --запросы

## Почему этот прибор перечисляет, а не судит

Первая редакция пыталась судить: брала редкие основы фразы и искала окно
источника, где они стоят рядом. Прогон по тексту `1c-publish-and-operate`
**до** правок — где шесть ложных отрицаний уже были известны поимённо —
нашёл одно из шести.

Две причины, и обе неустранимы механически:

  * **слово набора не равно слову источника.** Навык писал «как остановить
    автоудаление централизованно»; источник говорит «автоматическое удаление
    устаревших версий». Общей основы нет ни одной, а тема одна;
  * **отрицание чаще всего без глагола.** «готовых unit-файлов и процедур
    регистрации службы — это работа администратора ОС» отрицает наличие,
    не отрицая ничего грамматически.

Поэтому прибор делает то, что делается надёжно: **находит все места, где
набор утверждает отсутствие, и считает их.** Проверка каждого — запрос
к корпусу, и его задаёт человек или агент. Ценность в полноте переписи:
пропущенное отрицание не проверит никто, а список из шестидесяти строк
проверяется за один заход.

## Где он их находит

Два места, и первое даёт большинство:

  * **блок «Чего … нет»** в конце каждого справочника. Заголовок и есть
    отрицание: всё, что под ним, — утверждения об отсутствии, независимо
    от слов. Пять из шести грубых находок жили именно здесь;
  * **проза с оборотом отрицания** — «источник не описывает», «единственный
    способ», «ни одного». Указания («не рекомендуется», «не следует»)
    не считаются: это совет, а не утверждение о содержимом источника.

Отрицание внутри «ёлочек» — отрицание **источника**, и оно законно:
«не поддерживается автономным сервером» сказал источник. Такие пропускаются,
их посимвольную верность стережёт `check-quotes.py`.

## Чего этот прибор не умеет

  * **сказать, верно ли отрицание.** Он не открывает корпус вовсе;
  * **найти отрицание, спрятанное в утверждении.** «Настраивается только
    в конфигураторе» отрицает наличие второго пути, не говоря «нет».

С `--запросы` к каждой строке печатаются её редкие слова — заготовка
поискового запроса, не более того.
"""
import argparse
import os
import re
import sys
from pathlib import Path

# Про эту преамбулу см. check-sources.py: перенаправленный вывод берёт ANSI
# системы, и первый же знак вне cp1251 роняет отчёт трассировкой.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАВЫКИ = КОРЕНЬ / "skills"

ЁЛОЧКИ = re.compile(r"«[^»]*»", re.S)

# Заголовок блока отсутствий. Набор пишет его по-разному — «Чего в главе 22
# нет», «Чего в источниках нет», «Чего здесь нет», «Чего эти стандарты
# не покрывают», «Чего система стандартов о расширениях не говорит».
#
# Первая редакция требовала слова «нет» и на двух последних формах молчала:
# два блока из тридцати одного прибору не были видны, а невидимый блок
# не проверит никто — ровно то, ради чего этот прибор написан. Поймано
# 02.09.2026 сверкой числа блоков с числом справочников.
БЛОК = re.compile(
    r"^#{2,4}\s+[^\n]*\bчего\b[^\n]*"
    r"(?:\bнет\b|\bне\s+(?:говор|покрыв|описыв|зада|назыв|обеща)[а-яё]*)",
    re.IGNORECASE)
ЗАГОЛОВОК = re.compile(r"^#{1,6}\s")
ПУНКТ = re.compile(r"^\s*[-*]\s+")

# Обороты, которыми набор объявляет отсутствие в собственной прозе.
# «Не рекомендуется», «не следует», «не надо» сюда не входят: это указание,
# а не утверждение о содержимом источника.
ОТРИЦАНИЕ = re.compile(
    r"источник[а-яё]*\s+(?:\S+\s+){0,3}?(?:не|нигде|только)\b"
    r"|(?:не|нигде\s+не)\s+(?:описыва|даёт|дает|назван|называ|говор|содерж"
    r"|предусмотр|упомина|объясня|раскрыва|определя|приводит|указыва|знает"
    r"|расписыва|поясня)[а-яё]*"
    r"|(?:чего|что)\s+(?:в|у)\s+[^.\n]{0,50}\bнет\b"
    r"|\bнет\s+(?:ни\s+)?(?:способа|признака|правила|команды|перечня|ответа"
    r"|процедуры|описания|механизма|проверки)"
    r"|единственн(?:ый|ое|ая|ым|ого)"
    r"|\bни\s+одн(?:ого|ой|им)"
    r"|\bнечем\b|\bнеоткуда\b|\bи всё\b",
    re.IGNORECASE)

СЛОВО = re.compile(r"[а-яёa-zA-ZА-ЯЁ][а-яёa-zA-ZА-ЯЁ0-9_]{5,}")

# Слова, которые есть в любом тексте набора и запросом быть не могут.
# Глаголы отрицания сюда входят наравне со служебными: фразу «источник
# не описывает» они наполняют целиком, а запросом к корпусу быть не могут.
# Поймано тестом — первая редакция отдавала «описывает» поисковым словом.
ПУСТЫЕ = set("""
источник источника источники источнику источниках навык навыке навыка раздел
раздела разделе который которая которое которые данного данной данные
значение значения следует необходимо возможность возможности выполнить
выполняется система системы предприятие использование использовать например
правило правила поэтому отсюда однако вообще именно только всегда никогда
способ способа случае случай вопрос вопроса ответ ответа признак признака
перечень перечня описание описания механизм механизма процедура процедуры
команда команды сказано названо описано соседа глава главе главы
описывает описывают описать называет называют назвать говорит говорят
содержит содержат предусмотрено упоминает объясняет раскрывает определяет
приводит указывает расписывает поясняет знает единственный единственное
единственная требование требования проверки проверка
""".split())


def перепись(текст):
    """[(вид, строка)] — все утверждения об отсутствии в одном файле.

    Вид: «блок» — пункт под заголовком «Чего … нет»; «проза» — фраза
    с оборотом отрицания где угодно ещё.
    """
    без_кода = re.sub(r"```.*?```", " ", текст, flags=re.S)
    строки = без_кода.split("\n")
    out, в_блоке, пункт = [], False, []

    def сдать():
        if пункт:
            фраза = " ".join(" ".join(пункт).split())
            if фраза:
                out.append(("блок", фраза))
            пункт.clear()

    for строка in строки:
        if ЗАГОЛОВОК.match(строка):
            сдать()
            в_блоке = bool(БЛОК.match(строка))
            continue
        if в_блоке:
            if ПУНКТ.match(строка):
                сдать()
                пункт.append(ПУНКТ.sub("", строка).strip())
            elif строка.strip():
                пункт.append(строка.strip())
            else:
                сдать()
            continue
        # Проза вне блока: цитаты снимаем — отрицание в них принадлежит
        # источнику, а не набору.
        s = ЁЛОЧКИ.sub(" ", строка).strip()
        if not s or s.startswith("|"):
            continue
        for ф in re.split(r"(?<=[.;:])\s+", s):
            ф = ф.strip()
            if ф and ОТРИЦАНИЕ.search(ф):
                out.append(("проза", " ".join(ф.split())))
    сдать()
    return out


def запрос(фраза):
    """Заготовка поискового запроса: значимые слова строки без служебных."""
    out, видели = [], []
    for с in СЛОВО.findall(ЁЛОЧКИ.sub(" ", фраза)):
        н = с.lower().replace("ё", "е")
        if н in ПУСТЫЕ or н in видели:
            continue
        видели.append(н)
        out.append(с)
    return out[:5]


def навыки_на_диске():
    return [п.name for п in sorted(НАВЫКИ.iterdir())
            if п.is_dir() and (п / "SKILL.md").is_file()]


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    г = р.add_mutually_exclusive_group(required=True)
    г.add_argument("--навык")
    г.add_argument("--все", action="store_true")
    р.add_argument("--запросы", action="store_true",
                   help="печатать заготовку поискового запроса к каждой строке")
    р.add_argument("--молча", action="store_true")
    а = р.parse_args()

    имена = навыки_на_диске() if а.все else [а.навык]
    for имя in имена:
        if not (НАВЫКИ / имя).is_dir():
            raise SystemExit("нет навыка: %s" % имя)

    из_блоков, из_прозы, файлов = 0, 0, 0
    for имя in имена:
        for файл in sorted((НАВЫКИ / имя).rglob("*.md")):
            строки = перепись(файл.read_text(encoding="utf-8"))
            файлов += 1
            if not строки:
                continue
            if not а.молча:
                print("--- %s / %s" % (имя, файл.name))
            for вид, фраза in строки:
                if вид == "блок":
                    из_блоков += 1
                else:
                    из_прозы += 1
                if а.молча:
                    continue
                метка = "[блок]" if вид == "блок" else "[проза]"
                print("  %s %s" % (метка, фраза[:150] + ("…" if len(фраза) > 150 else "")))
                if а.запросы:
                    print("         запрос: %s" % ", ".join(запрос(фраза)))
            if not а.молча:
                print()

    всего = из_блоков + из_прозы
    print("навыков: %d, файлов прочитано: %d, утверждений об отсутствии: %d "
          "(из блоков «Чего нет»: %d, из прозы: %d)"
          % (len(имена), файлов, всего, из_блоков, из_прозы))
    if not файлов:
        print("ВНИМАНИЕ: вход пуст — прибор ничего не смотрел, и ноль находок "
              "об этом не говорит")
        return 2
    # Перепись — не приговор: каждая строка требует своего запроса к корпусу.
    # Красным код возврата не делаем.
    return 0


if __name__ == "__main__":
    sys.exit(main())
