"""Перепись параграфов главы руководства, у которых в наборе нет ни одного адреса.

    python tools/check-chapter-paragraphs.py 9 21 34
    python tools/check-chapter-paragraphs.py --карта

## Зачем, если есть `check-map-promises.py`

Прибор карты отвечает на вопрос «писали ли вообще»: один адрес главы
в разделе — и обещание засчитано. На вопрос «прочитана ли глава» он
не отвечает, и это записано в его ограничениях как работа человека.

22.09.2026 человек на этом ошибся. Карта с 06.09 писала про главу 9
«прочитана почти целиком, не взят один параграф», а без единого адреса
оставалось **около 28 тыс. знаков**: пессимистическая блокировка, две
таблицы режимов по СУБД, умолчание `РежимБлокировок` у `НачатьТранзакцию()`
(`Автоматический`), поведение смешанного режима. Нашлось это сверкой
параграфов главы с адресами набора — ею же в тот день найдены пробелы
в главах 20, 26, 29 и 34.

## Что он делает

Берёт главу из выгрузки руководства, режет её по заголовкам вида «9.2.3.4.»
и оставляет **листья** — параграфы без детей. Для каждого листа ищет
в наборе адрес `§9.2.3.4` или его подраздел. Диапазоны и перечни
(«§9.1.2–9.1.4, 9.2.2.3») раскрываются по концам: знак параграфа в наборе
стоит только у первого адреса.

## Почему перечисляет, а не судит

Отсутствие адреса — **не** отсутствие разбора. Часть справочников
цитирует главу без номеров параграфов: глава 26 при проверке 22.09
оказалась разобрана по содержанию почти целиком, а адресов у неё было два.
Поэтому прибор печатает кандидатов, а решение по каждому — чтением.
Код возврата 0 при любом числе кандидатов; 2 — если глава не найдена
в выгрузке: ноль кандидатов у прибора, до которого не дошёл вход, выглядел
бы полным благополучием.

## Чего он не умеет

  * **увидеть разбор без адреса** — см. выше;
  * **разобрать заголовок, склеенный с текстом иначе, чем «N.N. Слово».**
    Выгрузка ИТС кладёт заголовок и первое предложение в одну строку;
    параграф, чей заголовок начинается не с заглавной буквы, кавычки
    или латиницы, пропадёт из переписи;
  * **сказать, достаточно ли разобран лист, у которого адрес есть.**
    Один адрес на восьми тысячах знаков — след, а не разбор.
"""
import argparse
import importlib.util
import os
import re
import sys
from pathlib import Path

# Про эту преамбулу см. check-sources.py: перенаправленный вывод берёт ANSI
# системы, и первый же знак вне cp1251 роняет отчёт трассировкой.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАВЫКИ = КОРЕНЬ / "skills"
КАРТА = (НАВЫКИ / "developing-1c-configurations" / "references" / "architecture.md")

АДРЕС = re.compile(r"§(\d+(?:\.\d+)+)((?:\s*[–,-]\s*\d+(?:\.\d+)+)*)")
НОМЕР = re.compile(r"\d+(?:\.\d+)+")


def адреса(тексты):
    """Множество адресов «9.2.3.4» из текстов, диапазоны — по концам."""
    out = set()
    for т in тексты:
        for м in АДРЕС.finditer(т):
            out.add(м.group(1).rstrip("."))
            for н in НОМЕР.findall(м.group(2)):
                out.add(н.rstrip("."))
    return out


def листья(текст, глава):
    """[(номер, знаков, заголовок)] параграфов главы, у которых нет детей."""
    т = " ".join(текст.split())
    # Заголовок захватывается заглядыванием вперёд, а не поглощением:
    # в выгрузке «9.1. Механизм транзакций 9.1.1. Общие сведения» название
    # родителя тянется до точки и съело бы начало ребёнка — первая
    # редакция так теряла §9.1.1, §9.2.1, §9.2.3.1 и §9.4.1.
    заголовки = list(re.finditer(
        r"\b(%s(?:\.\d+)+)\.(?=\s+([А-ЯЁ«A-Z][^.●]{0,50}))" % re.escape(глава), т))
    out = []
    for к, з in enumerate(заголовки):
        номер = з.group(1)
        следующий = заголовки[к + 1] if к + 1 < len(заголовки) else None
        if следующий and следующий.group(1).startswith(номер + "."):
            continue
        конец = следующий.start() if следующий else len(т)
        out.append((номер, конец - з.start(), з.group(2).strip()))
    return out


def без_адреса(лист_список, набор_адресов):
    """Листья, для которых в наборе нет ни их адреса, ни адреса подраздела."""
    return [(н, р, з) for н, р, з in лист_список
            if not any(а == н or а.startswith(н + ".") for а in набор_адресов)]


def тексты_набора():
    """Тексты всех .md набора, кроме самой карты: её «не взяты» — не разбор."""
    карта = Path(КАРТА).resolve()
    return [п.read_text(encoding="utf-8") for п in sorted(НАВЫКИ.rglob("*.md"))
            if п.resolve() != карта]


def главы_руководства():
    """{номер главы: текст} из выгрузки руководства разработчика."""
    спец = importlib.util.spec_from_file_location(
        "its_search", КОРЕНЬ / "tools" / "its-search.py")
    мод = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(мод)
    out = {}
    for заголовок, текст, _адрес in мод.загрузить("devguide"):
        м = re.match(r"Глава (\d+)\.", заголовок)
        if м:
            out[м.group(1)] = текст
    return out


def главы_карты():
    спец = importlib.util.spec_from_file_location(
        "check_map_promises", КОРЕНЬ / "tools" / "check-map-promises.py")
    мод = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(мод)
    return sorted({г for главы, _н, _о in мод.строки_карты() for г in главы},
                  key=int)


def main(argv=None):
    разбор = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    разбор.add_argument("главы", nargs="*", help="номера глав")
    разбор.add_argument("--карта", action="store_true",
                        help="все главы из карты architecture.md")
    арг = разбор.parse_args(argv)
    номера = главы_карты() if арг.карта else арг.главы
    if not номера:
        разбор.error("укажите номера глав или --карта")

    руководство = главы_руководства()
    набор_адресов = адреса(тексты_набора())
    пропало = [н for н in номера if н not in руководство]
    if пропало:
        print("ВНИМАНИЕ: в выгрузке руководства нет глав %s — прибор смотрел "
              "не туда или выгрузки нет" % ", ".join(пропало))
        return 2
    for н in номера:
        лл = листья(руководство[н], н)
        без = без_адреса(лл, набор_адресов)
        всего = sum(р for _н, р, _з in лл)
        голых = sum(р for _н, р, _з in без)
        print("глава %s: листьев %d, без адреса %d — %d знаков из %d"
              % (н, len(лл), len(без), голых, всего))
        for номер, размер, заголовок in без:
            print("   §%-12s %6d  %s" % (номер, размер, заголовок))
    return 0


if __name__ == "__main__":
    sys.exit(main())
