"""Карта глав руководства против содержимого разделов: сдержано ли обещание.

`architecture.md` раздаёт главы руководства разработчика, которым нет места
в системе стандартов: «глава 29 — разделу `1c-integrations`». Читается это
как обещание, и **набор попадался на нём четырежды**: главы 20, 23, 32
и 29 были розданы и не написаны. Три первых закрыты 02.09.2026, четвёртая
найдена 05.09 — она же была самой большой (204 тыс. знаков) и единственной,
о которой не говорил ни один список отсутствий.

    python tools/check-map-promises.py

## Почему этот прибор надёжен там, где прибор полноты врал

`check-coverage.py` спрашивает «названа ли тема», и на этом вопросе ошибался
трижды подряд, всегда в сторону благополучия: слова подзаголовков главы
(«Общие сведения», «Сообщения», «Настройка») есть в любом тексте набора,
а предмет главы засчитывался по одному вхождению — у главы 29 им оказалась
строка **поисковых слов** соседнего справочника.

Здесь вопрос другой и машинный: **сколько адресов вида `§29.4` стоит
в разделе, которому глава отдана.** Набор обязан носить адрес при каждом
утверждении, поэтому разобранная глава оставляет следы, а необработанная
не оставляет ни одного. Замер 05.09.2026 по одиннадцати парам «глава —
раздел»:

    сдержанные обещания   §20 — 17,  §22 — 10,  §23 — 13,  §32 — 13,  §30 — 203,
                          §25 у `1c-extensions` — 2
    пустые обещания       §11, §12, §13, §24, §29 и §25 у `1c-metadata-objects`
                          — ноль у каждой

Ни одного пересечения. Пара §25 показывает, зачем счёт идёт по паре, а не
по главе: одну и ту же главу два раздела держат по-разному, и строка карты,
где они стояли вместе, скрывала это — прибор нашёл расхождение на первом же
прогоне, в тот же час, когда карта была переписана. Прибор различает не «хорошо ли написано», а «писали
ли вообще» — и на этот вопрос отвечает точно.

## Чего он не умеет

  * **сказать, полна ли глава.** Десять адресов из главы в сорок
    подзаголовков — это следы, а не разбор. Соразмерность по-прежнему
    проверяется человеком;
  * **заметить главу, разобранную без адресов.** Такой файл нарушал бы
    правило набора «утверждение несёт адрес», и его поймает `check-quotes.py`,
    а не этот прибор;
  * **проверить главы вне карты.** Он читает ровно ту таблицу, что стоит
    в `architecture.md`, и молчит обо всём остальном.

Третий столбец таблицы — обещание словами: «целиком» либо оговорка о том,
что взято частично. Прибор сверяет столбец со следами и ругается на оба
расхождения: обещано «целиком», а следов нет — нарушение; оговорка стоит,
а следов много — оговорка устарела.
"""
import io
import os
import re
import sys
from pathlib import Path

# Про эту преамбулу см. check-sources.py: перенаправленный вывод берёт ANSI
# системы, и первый же знак вне cp1251 роняет отчёт трассировкой.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАВЫКИ = КОРЕНЬ / "skills"
КАРТА = (НАВЫКИ / "developing-1c-configurations" / "references" / "architecture.md")

ШАПКА = "| Глава руководства | Раздел навыка | Что взято |"
ГЛАВА = re.compile(r"\b(\d{1,2})\s+[А-ЯЁ]")
НАВЫК = re.compile(r"`([a-z0-9-]+)`")

# Минимум строк в таблице. Прибор читает разметку чужого файла, и если
# таблица переедет или сменит форму, он обязан упасть, а не отчитаться
# «нарушений 0» о ненайденном. Ноль находок у прибора, до которого не дошёл
# вход, выглядит как полное благополучие — этой ошибки набор уже наелся.
МИНИМУМ_СТРОК = 6


def строки_карты(текст=None):
    """[(номера глав, имена навыков, обещание третьего столбца)] из таблицы."""
    текст = текст if текст is not None else КАРТА.read_text(encoding="utf-8")
    if ШАПКА not in текст:
        raise SystemExit("в %s нет таблицы карты глав (шапка изменилась?)"
                         % КАРТА.name)
    хвост = текст.split(ШАПКА, 1)[1]
    out = []
    for строка in хвост.split("\n")[1:]:
        строка = строка.strip()
        if not строка.startswith("|"):
            break
        ячейки = [я.strip() for я in строка.strip("|").split("|")]
        if len(ячейки) != 3 or set(ячейки[0]) <= set("-: "):
            continue
        главы = ГЛАВА.findall(ячейки[0])
        навыки = НАВЫК.findall(ячейки[1])
        if главы and навыки:
            out.append((главы, навыки, ячейки[2]))
    return out


def следы(глава, навык):
    """Сколько адресов вида «§29.4» из этой главы стоит в этом разделе."""
    каталог = НАВЫКИ / навык
    if not каталог.is_dir():
        return None
    образец = re.compile("§" + глава + r"\.\d")
    return sum(len(образец.findall(п.read_text(encoding="utf-8")))
               for п in каталог.rglob("*.md"))


def проверить(строки):
    """[(вид, глава, навык, следов, обещание)] — расхождения карты и следов."""
    находки = []
    for главы, навыки, обещание in строки:
        целиком = обещание.lower().startswith("целиком")
        for глава in главы:
            for навык in навыки:
                найдено = следы(глава, навык)
                if найдено is None:
                    находки.append(("нет такого раздела", глава, навык,
                                    0, обещание))
                elif целиком and найдено == 0:
                    находки.append(("пустое обещание", глава, навык,
                                    найдено, обещание))
                elif not целиком and найдено:
                    находки.append(("оговорка устарела", глава, навык,
                                    найдено, обещание))
    return находки


def main():
    строки = строки_карты()
    if len(строки) < МИНИМУМ_СТРОК:
        print("ВНИМАНИЕ: в таблице карты найдено строк: %d — меньше %d. "
              "Разметка изменилась, прибор смотрел не туда"
              % (len(строки), МИНИМУМ_СТРОК))
        return 2
    находки = проверить(строки)
    for вид, глава, навык, найдено, обещание in находки:
        print("[!] глава %s → %s: %s (следов §%s.x: %d, в карте «%s»)"
              % (глава, навык, вид, глава, найдено, обещание[:60]))
    глав = sum(len(г) for г, _н, _о in строки)
    print("строк карты: %d, глав: %d, расхождений: %d"
          % (len(строки), глав, len(находки)))
    return 1 if находки else 0


if __name__ == "__main__":
    sys.exit(main())
