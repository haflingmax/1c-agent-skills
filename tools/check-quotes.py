#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Сверяет цитаты навыков с корпусом ИТС: то, что в «ёлочках», есть в источнике.

Зачем. Разбор шести разделов подряд дал один и тот же класс дефекта: дословные
цитаты почти никогда не врут, врёт **проза вокруг них**. Но у этого класса есть
механически ловимая половина — случаи, когда правится сама цитата:

  - слово внутри кавычек просклонено под фразу навыка
    («повысить устойчивость…» → «ради устойчивости…»);
  - многоточие съело несущее слово («кроме проверки наличия роли», «только
    для разработчиков», «без необходимости включения»);
  - цитата собрана из двух мест документа и подана как одна;
  - цитата приписана не тому стандарту.

Всё это находится сверкой с корпусом и не требует чтения. Прозу вокруг цитат
инструмент не судит — это работа шага опровержения.

Как считается. Из тела и справочников навыка вынимаются фрагменты в «ёлочках».
Фрагмент разбивается по многоточию на части; каждая часть длиной от порога
ищется в тексте стандартов, названных в том же абзаце. Сравнение идёт
по нормализованному тексту: регистр, ё/е, дефисы, кавычки и пробелы приведены
к одному виду, разметка снята.

Чего инструмент намеренно НЕ делает:

  - не судит короткие фрагменты (порог `--минимум`): «Чтение», «не следует»,
    имена методов в кавычках дают шум, а не находки;
  - не ищет по всему корпусу, если в абзаце назван стандарт: цитата, найденная
    в чужом документе, — это находка, а не оправдание;
  - не падает, если корпус не выгружен: без `_its/` он говорит об этом
    и возвращает 0. Отсутствие данных — не нарушение набора.

Использование:
    python tools/check-quotes.py
    python tools/check-quotes.py --навык 1c-access-rights --подробно
"""
import argparse
import importlib.util
import os
import re
import sys

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
НАВЫКИ = os.path.join(КОРЕНЬ, "skills")
КОРПУС = os.path.join(КОРЕНЬ, "_its", "v8std-full.json")

# Цитата набора — в «ёлочках». Внутренние „лапки“ живут внутри и не считаются.
ЦИТАТА = re.compile("«([^«»]{1,4000})»")
# Номер стандарта во всех формах, принятых в наборе: stdNNN, «стандарт NNN»,
# заголовок справочника «(NNN, пункт …)» и выделенный номер «**NNN**».
НОМЕР = re.compile(
    r"(?:std|стандарт[а-яё]*\s+)(\d{3})"
    r"|\((\d{3})(?=[,)])"
    r"|\*\*(\d{3})\*\*", re.I)
МНОГОТОЧИЕ = re.compile(r"…|\.\.\.")


def нормализовать(s):
    """Приводит текст к виду, в котором сравнение осмысленно.

    Снимает разметку навыка (** ` [] ()), уравнивает ё/е, все виды кавычек,
    дефисов и пробелов. Регистр — вниз. Это не «размывание»: правка слова
    внутри кавычек нормализацию переживает и остаётся видимой.
    """
    # Разметка markdown: жирный, код, блочная цитата «> » в начале строк
    # и экранирование «\*», без которого markdown съел бы звёздочку как
    # разметку. В источнике звёздочка стоит без обратной косой, и сверка
    # проваливалась бы на ней, а не на цитате.
    s = re.sub(r"^\s*>\s?", " ", s, flags=re.M)
    s = s.replace("\\*", "*").replace("\\_", "_")
    s = s.replace("**", " ").replace("`", " ")
    s = s.replace("ё", "е").replace("Ё", "Е")
    for тире in "–—‒−":
        s = s.replace(тире, "-")
    for кавычка in "«»„“”\"'":
        s = s.replace(кавычка, " ")
    s = re.sub(r"[\s ]+", " ", s)
    # Разметка навыка стояла вплотную к знакам препинания: «десятков**)»
    # после снятия ** давало «десятков )», и сверка проваливалась не
    # на цитате, а на пробеле, который сама же и внесла.
    s = re.sub(r"\s+([,.;:!?)»])", r"\1", s)
    s = re.sub(r"([(«])\s+", r"\1", s)
    return s.strip().lower()


def корпуса():
    """(по номеру std, общий стог всех корпусов) или (None, None), если выгрузки нет.

    Загрузка — тем же кодом, что и у `its-search.py`: у корпусов свой формат
    и свой перечень баз, и держать вторую его копию значит однажды разойтись.
    Первый словарь нужен для адресной сверки «цитата приписана std724»,
    второй — чтобы не ругаться на законные цитаты из руководства разработчика
    и методических материалов, у которых номера стандарта нет вовсе.
    """
    поиск = os.path.join(КОРЕНЬ, "tools", "its-search.py")
    if not os.path.isfile(поиск):
        return None, None
    спец = importlib.util.spec_from_file_location("its_search", поиск)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except Exception:
        return None, None

    по_номеру, стог = {}, []
    for имя in модуль.БАЗЫ:
        try:
            документы = модуль.загрузить(имя)
        except Exception:
            документы = []
        for _заголовок, текст, _адрес in документы:
            н = нормализовать(текст)
            стог.append(н)
            if имя == "v8std":
                м = re.search(r"#std(\d{3})", текст)
                if м:
                    по_номеру.setdefault(м.group(1), н)
    if not по_номеру and not стог:
        return None, None
    return по_номеру, "\n".join(стог)


def номера(текст):
    """Номера стандартов, названные в тексте, в любой из принятых форм."""
    из_групп = set()
    for кортеж in НОМЕР.findall(текст):
        for г in (кортеж if isinstance(кортеж, tuple) else (кортеж,)):
            if г:
                из_групп.add(г)
    return из_групп


def абзацы(текст):
    """Абзацы файла: цитата ищется в тех стандартах, что названы рядом с ней."""
    return re.split(r"\n\s*\n", текст)


def короткий_путь(путь):
    """Путь от корня репозитория, а если файл на другом диске — абсолютный.

    На Windows `relpath` не сокращает, а падает, когда цель и корень лежат
    на разных дисках: репозиторий на D:, временный каталог на C:. Ронять
    проверку из-за оформления вывода нельзя.
    """
    try:
        return os.path.relpath(путь, КОРЕНЬ)
    except ValueError:
        return путь


def проверить_файл(путь, тексты, стог, минимум):
    найдено = []
    сырое = open(путь, encoding="utf-8").read()
    # Блоки кода — не проза набора: там кавычки принадлежат языку 1С.
    сырое = re.sub(r"```.*?```", "", сырое, flags=re.S)

    # Стандарты, названные где-либо в файле. Абзац — не всегда полная
    # адресация: правило может стоять под заголовком «Стандарт 532», а номер
    # соседа — в скобке внутри пункта. Поэтому находкой считается цитата,
    # которой нет ни в одном стандарте файла, а не та, что нашлась не в том
    # абзаце.
    вфайле = [н for н in sorted(номера(сырое)) if н in тексты]

    for абзац in абзацы(сырое):
        в_абзаце = [н for н in номера(абзац) if н in тексты]
        где = в_абзаце or вфайле
        if not где:
            continue
        for цитата in ЦИТАТА.findall(абзац):
            for часть in МНОГОТОЧИЕ.split(цитата):
                ч = нормализовать(часть)
                # хвосты пунктуации от обрыва цитаты
                ч = ч.strip(" ,.;:!?-")
                if len(ч) < минимум:
                    continue
                if any(ч in тексты[н] for н in где):
                    continue
                if в_абзаце and any(ч in тексты[н] for н in вфайле):
                    continue
                # Цитата может быть законной и не из системы стандартов:
                # набор цитирует руководство разработчика и методические
                # материалы, у которых номера std нет. Ругаться на них —
                # значит подменять находку отсутствием данных.
                if стог and ч in стог:
                    continue
                # может быть, фрагмент есть, но в другом стандарте — это тоже
                # находка, но её надо назвать иначе
                чужой = [н for н in тексты if ч in тексты[н]]
                найдено.append({
                    "файл": короткий_путь(путь),
                    "стандарты": где,
                    "фрагмент": часть.strip(),
                    "чужой": чужой[:3],
                })
    return найдено


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--навык", help="проверить один навык, а не все")
    р.add_argument("--минимум", type=int, default=40,
                   help="не судить фрагменты короче стольких знаков (по умолчанию 40)")
    р.add_argument("--подробно", action="store_true")
    а = р.parse_args()

    тексты, стог = корпуса()
    if тексты is None:
        print("[предупреждение] корпуса ИТС не выгружены — сверка цитат "
              "не выполнялась")
        return 0

    имена = [а.навык] if а.навык else sorted(
        и for и in os.listdir(НАВЫКИ)
        if os.path.isdir(os.path.join(НАВЫКИ, и)))

    всего, находки = 0, []
    for имя in имена:
        каталог = os.path.join(НАВЫКИ, имя)
        for корень, _, файлы in os.walk(каталог):
            for ф in sorted(файлы):
                if not ф.endswith(".md"):
                    continue
                всего += 1
                находки += проверить_файл(os.path.join(корень, ф), тексты,
                                          стог, а.минимум)

    for н in находки:
        print("[!] %s — цитата не найдена в %s" %
              (н["файл"], ", ".join("std" + s for s in н["стандарты"])))
        print("    «%s»" % (н["фрагмент"][:160]))
        if н["чужой"]:
            print("    но найдена в: %s" % ", ".join("std" + s for s in н["чужой"]))
        if а.подробно:
            print("    нормализованный вид: %s" % нормализовать(н["фрагмент"])[:160])

    print("\nфайлов проверено: %d, стандартов в корпусе: %d, "
          "цитат не сошлось: %d" % (всего, len(тексты), len(находки)))
    return 1 if находки else 0


if __name__ == "__main__":
    sys.exit(main())
