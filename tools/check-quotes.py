КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
НАВЫКИ = os.path.join(КОРЕНЬ, "skills")
КОРПУС = os.path.join(КОРЕНЬ, "_its", "v8std-full.json")

# Цитата набора — в «ёлочках». Внутренние „лапки“ живут внутри и не считаются.
ЦИТАТА = re.compile("«([^«»]{1,4000})»")
# Номер стандарта во всех формах, принятых в наборе: stdNNN, «стандарт NNN»,
# заголовок справочника «(NNN, пункт …)» и выделенный номер «**NNN**».
НОМЕР = re.compile(
    r"(?:std|стандарт[а-яё]*\s+)(\d{3})"
    r"|\((\d{3})(?=[,)])"
    r"|\*\*(\d{3})\*\*", re.I)
# Методический материал ИТС: номер четырёхзначный и живёт в тех же формах,
# что и стандарт, плюс после слова «методичка/материал/статья/документ».
# Голое четырёхзначное число ссылкой не считается намеренно: иначе год
# в прозе («в 2026 году») превратится в номер документа.
МЕТОДИЧКА = re.compile(
    r"(?:методич[а-яё]*|материал[а-яё]*|стать[а-яё]+|документ[а-яё]*)\s+(\d{4})"
    r"|\((\d{4})(?=[,)])"
    r"|\*\*(\d{4})\*\*"
    # Перечисление источников в шапке справочника: «2863 «Заголовок»».
    # Ключевое слово стоит только перед первым номером, остальные идут
    # через запятую, и узнаются они по кавычке следом за номером.
    r'|(\d{4})(?=\s+«)'
    # Продолжение перечисления: «методички 3093, 2913, 4049»
    # и «2866 и 2867». Ключевое слово стоит только перед первым.
    r'|(?<=\d, )(\d{4})'
    r'|(?<=\d и )(\d{4})', re.I)
МНОГОТОЧИЕ = re.compile(r"…|\.\.\.")


def _склеить_имя(m):
    """Склейка «Имя.Метод», разорванная переносом строки, — и только она.

    Признак составного имени — заглавная внутри слова слева от точки.
    Без этой проверки правило склеивало и границу предложения.
    """
    левое = m.group("лево")
    if re.search(r"[a-zа-яё][A-ZА-ЯЁ]", левое):
        return левое + "."
    return m.group(0)


def нормализовать(s):
    """Приводит текст к виду, в котором сравнение осмысленно.

    Снимает разметку навыка (** ` [] ()), уравнивает ё/е, все виды кавычек,
    дефисов и пробелов. Регистр — вниз. Это не «размывание»: правка слова
    внутри кавычек нормализацию переживает и остаётся видимой.
    """
    # Разметка markdown: жирный, код, блочная цитата «> » в начале строк
    # и экранирование «\*», без которого markdown съел бы звёздочку как
    # разметку. В источнике звёздочка стоит без обратной косой, и сверка
    # проваливалась бы на ней, а не на цитате.
    s = re.sub(r"^\s*>\s?", " ", s, flags=re.M)
    s = s.replace("\\*", "*").replace("\\_", "_")
    s = s.replace("**", " ").replace("`", " ")
    s = s.replace("ё", "е").replace("Ё", "Е")
    # U+2011 (неразрывный дефис) — рабочий знак выгрузки ИТС: им набрано
    # тире почти во всех перечнях корпуса. В списке его не было, и цитата,
    # набранная обычным тире, расходилась с источником на одном знаке —
    # притом что тут же рядом обещано уравнивание всех видов дефисов.
    for тире in "–—‒−‑":
        s = s.replace(тире, "-")
    for кавычка in "«»„“”\"'":
        s = s.replace(кавычка, " ")
    # Якорь сноски: «(*)» посреди предложения и одиночная звёздочка,
    # приклеенная к слову («объекта*»). Это разметка ИТС, а не текст правила.
    # Продолжение комментария в примерах кода: выгрузка ИТС склеивает
    # многострочный комментарий в одну строку, и «//» остаётся посреди
    # предложения. Набор цитирует текст правила, а не разметку примера.
    s = re.sub(r"(?<=\s)//\s+", "", s)
    s = s.replace("(*)", " ")
    s = re.sub(r"(?<=\w)\s*\*(?=[\s.,;:)»]|$)", "", s)
    # Маркер перечня, попавший в начало перенесённой строки после двоеточия
    # или точки с запятой: в источнике пункт идёт сплошным текстом.
    s = re.sub(r"([:;])\s*\n\s*[-*+]\s+", r"\1 ", s)
    s = re.sub(r"[\s ]+", " ", s)
    # Разметка навыка стояла вплотную к знакам препинания: «десятков**)»
    # после снятия ** давало «десятков )», и сверка проваливалась не
    # на цитате, а на пробеле, который сама же и внесла.
    s = re.sub(r"\s+([,.;:!?)»])", r"\1", s)
    s = re.sub(r"([(«])\s+", r"\1", s)
    # Тот же случай, но с дефисом: «**PATCH**-запроса» после снятия ** давало
    # «patch -запроса». Правило нарочно узкое — дефис обязан быть приклеен
    # к следующему слову. Тире между словами («канал ‑ логический адрес»)
    # им не задевается: там за дефисом стоит пробел.
    s = re.sub(r"\s+-(?=[A-Za-zА-Яа-яЁё0-9])", "-", s)
    # Составное имя, разорванное выгрузкой ИТС: «ИнформацияОбОшибке .
    # ЯвляетсяОшибкойКатегории». Склейка нарочно узкая — только когда
    # с обеих сторон точки стоит CamelCase. Общее правило «снять пробелы
    # вокруг точки» здесь недопустимо: 34 из 67 настоящих находок отличаются
    # от источника ТОЛЬКО знаками и пробелами, и слепой к пунктуации
    # нормализатор молча съел бы половину улова. Порядок важен: склейка
    # идёт после снятия пробелов у скобок, иначе «строк ). в» и «строк. в»
    # разойдутся снова.
    #
    # Поправка 26.08.2026: комментарий выше обещал «с обеих сторон CamelCase»,
    # а правило проверяло только правую сторону и склеивало любую границу
    # предложения вида «…данных. Диаграмма». Из-за этого цитата, у которой
    # в корпусе на той же границе стоит маркер перечня, расходилась
    # с источником на ровном месте. Теперь левая сторона проверяется тоже.
    s = re.sub(r"(?P<лево>[A-Za-zА-Яа-я0-9]+)\s*\.\s*(?=[A-ZА-Я][A-Za-zА-Яа-я])",
               _склеить_имя, s)
    return s.strip().lower()


def разрешённые():
    """Нормализованные фрагменты из `tools/quotes-outside-its.md`.

    Файл называет цитаты, которых в корпусах ИТС нет по праву: вывод
    платформы, снятый прогоном, и собственный отозванный текст набора
    в поправке. Список короткий и пополняется обдуманно — он снимает
    единственную механическую защиту от выдуманной цитаты.
    """
    путь = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "quotes-outside-its.md")
    if not os.path.exists(путь):
        return []
    сырое = open(путь, encoding="utf-8").read()
    # Запись читается по всему тексту, а не построчно: она может занимать
    # две строки, и построчный разбор терял бы её молча — ровно тот случай,
    # ради которого список и заведён.
    из_файла = [нормализовать(ф).strip(" ,.;:!?-")
                for ф in re.findall(r"^- «(.+?)»", сырое, re.M | re.S)]
    return [ф for ф in из_файла if ф]


def корпуса():
    """(по номеру std, общий стог всех корпусов) или (None, None), если выгрузки нет.

    Загрузка — тем же кодом, что и у `its-search.py`: у корпусов свой формат
    и свой перечень баз, и держать вторую его копию значит однажды разойтись.
    Первый словарь нужен для адресной сверки «цитата приписана std724»,
    второй — чтобы не ругаться на законные цитаты из руководства разработчика
    и методических материалов, у которых номера стандарта нет вовсе.
    """
    поиск = os.path.join(КОРЕНЬ, "tools", "its-search.py")
    if not os.path.isfile(поиск):
        return None, None
    спец = importlib.util.spec_from_file_location("its_search", поиск)
    модуль = importlib.util.module_from_spec(спец)
    try:
        спец.loader.exec_module(модуль)
    except Exception:
        return None, None

    по_номеру, стог = {}, []
    for имя in модуль.БАЗЫ:
        try:
            документы = модуль.загрузить(имя)
        except Exception:
            документы = []
        for _заголовок, текст, _адрес in документы:
            н = нормализовать(текст)
            стог.append(н)
            if имя == "v8std":
                м = re.search(r"#std(\d{3})", текст)
                if м:
                    по_номеру.setdefault(м.group(1), н)
            elif имя == "metod8dev":
                # У методичек номер живёт в адресе: /content/NNNN/hdoc.
                # Заголовки у них сплошь «Пример всех стилей», по ним
                # документ не опознать.
                м = re.search(r"/content/(\d{3,5})/", str(_адрес))
                if м:
                    по_номеру.setdefault("м" + м.group(1), н)
    if not по_номеру and not стог:
        return None, None
    return по_номеру, "\n".join(стог)


def номера(текст):
    """Номера стандартов, названные в тексте, в любой из принятых форм."""
    из_групп = set()
    for кортеж in НОМЕР.findall(текст):
        for г in (кортеж if isinstance(кортеж, tuple) else (кортеж,)):
            if г:
                из_групп.add(г)
    return из_групп


def методички(текст):
    """Номера методических материалов, названные в тексте, с приставкой «м».

    Приставка нужна, чтобы ключи не столкнулись со стандартами: у обоих
    номера числовые, и «532» стандарта не должно совпасть с методичкой.
    """
    из_групп = set()
    for кортеж in МЕТОДИЧКА.findall(текст):
        for г in (кортеж if isinstance(кортеж, tuple) else (кортеж,)):
            if г:
                из_групп.add("м" + г)
    return из_групп


def адреса(текст):
    """Все названные в тексте документы: и стандарты, и методички."""
    return номера(текст) | методички(текст)


def подпись(ключ):
    """Как назвать документ в отчёте: std532 или «методичка 4320»."""
    return "методичка " + ключ[1:] if ключ.startswith("м") else "std" + ключ


def абзацы(текст):
    """Абзацы файла: цитата ищется в тех стандартах, что названы рядом с ней."""
    return re.split(r"\n\s*\n", текст)


def заголовки_набора():
    """Названия разделов всех навыков, нормализованные.

    Набор адресует свои же разделы по имени в «ёлочках» — «см. раздел
    «Что выяснить до первой правки» в ядре». Для сверки цитат это неотличимо
    от цитаты из ИТС, и до сих пор спасал только порог в сорок знаков:
    названия короче. Длинное название сломало бы проверку на ровном месте,
    поэтому имя собственного раздела законно и находкой не считается.

    Сверка строгая — совпадение целиком, а не вхождение: иначе под именем
    раздела прошла бы любая цитата, начинающаяся с тех же слов.
    """
    имена = set()
    if not os.path.isdir(НАВЫКИ):
        return имена
    for корень, _, файлы in os.walk(НАВЫКИ):
        for ф in файлы:
            if not ф.endswith(".md"):
                continue
            текст = open(os.path.join(корень, ф), encoding="utf-8").read()
            for з in re.findall(r"(?m)^#{1,6}\s+(.+?)\s*$", текст):
                имена.add(нормализовать(з).strip(" ,.;:!?-"))
    return {и for и in имена if и}


def разделы(текст):
    """Файл кусками от одного заголовка «## » до следующего.

    Единица адресации в наборе — раздел, а не абзац: источник называется
    в первой фразе раздела, а в абзацах ниже стоят перекрёстные ссылки
    на соседей. Абзац как окно давал ложные находки подмены адреса.
    """
    куски = re.split(r"(?m)^(?=## )", текст)
    return [к for к in куски if к.strip()]


def без_маркеров(s):
    """Тот же текст, но без маркеров перечня и разделителей пунктов.

    Нужна ровно для одного: отличить «набор перенёс перечень маркерами»
    от «набор поправил слова». Первое — оформление, второе — находка.

    Маркер выгрузки ИТС — «●» (U+25CF). Первая редакция снимала «•» и «·»,
    которых в корпусе нет, и класс не срабатывал ни разу: перечни из
    руководства уходили в строгие находки. Проверено 26.08.2026 на восьми
    цитатах раздела отчётов.
    """
    s = re.sub(r"[·•●○◦▪]", " ", s)
    s = re.sub(r"(?<=\s)-\s+", " ", s)
    s = re.sub(r"[\s]+", " ", s)
    return s.strip()


def короткий_путь(путь):
    """Путь от корня репозитория, а если файл на другом диске — абсолютный.

    На Windows `relpath` не сокращает, а падает, когда цель и корень лежат
    на разных дисках: репозиторий на D:, временный каталог на C:. Ронять
    проверку из-за оформления вывода нельзя.
    """
    try:
        return os.path.relpath(путь, КОРЕНЬ)
    except ValueError:
        return путь


def проверить_файл(путь, тексты, стог, минимум, разрешено=(), свои=()):
    найдено = []
    сырое = open(путь, encoding="utf-8").read()
    # Блоки кода — не проза набора: там кавычки принадлежат языку 1С.
    сырое = re.sub(r"```.*?```", "", сырое, flags=re.S)

    # Стандарты, названные где-либо в файле. Абзац — не всегда полная
    # адресация: правило может стоять под заголовком «Стандарт 532», а номер
    # соседа — в скобке внутри пункта. Поэтому находкой считается цитата,
    # которой нет ни в одном стандарте файла, а не та, что нашлась не в том
    # абзаце.
    вфайле = [н for н in sorted(адреса(сырое)) if н in тексты]

    # Заголовок раздела — единственное место, где номер документа стоит
    # как заявка на источник, а не как перекрёстная ссылка: набор пишет
    # «## Итог по полю-характеристике (4320)». Только по нему и судим
    # о подмене адреса; номера внутри прозы сплошь и рядом отсылают
    # к соседям, и первые две редакции этой проверки на них и ловились.
    пары = []
    for раздел in разделы(сырое):
        строки = раздел.split(chr(10), 1)
        заголовок = [н for н in адреса(строки[0])
                     if н in тексты] if строки[0].startswith("## ") else []
        for абзац in абзацы(раздел):
            пары.append((заголовок, абзац))

    for в_заголовке, абзац in пары:
        в_абзаце = [н for н in адреса(абзац) if н in тексты]
        где = в_абзаце or в_заголовке or вфайле
        # Пустой «где» раньше означал пропуск абзаца целиком, и это была
        # тихая дыра: файл, не называющий ни одного стандарта, не проверялся
        # вовсе, а итог всё равно писал «цитат не сошлось: 0». Так ушли
        # непроверенными 160 цитат в восьми файлах — все из руководства
        # разработчика, у которого номера std нет по устройству.
        # Теперь адресной сверки для таких абзацев нет (не с чем сверять),
        # а сверка с общим стогом — есть.
        for цитата in ЦИТАТА.findall(абзац):
            for часть in МНОГОТОЧИЕ.split(цитата):
                ч = нормализовать(часть)
                # хвосты пунктуации от обрыва цитаты
                ч = ч.strip(" ,.;:!?-")
                if len(ч) < минимум:
                    continue
                if any(ч in тексты[н] for н in где):
                    continue
                # Цитата есть, но не там, куда её адресует абзац. Прежде это
                # молча проходило: сверка отступала на список номеров всего
                # файла. Именно так три подмены номера дожили до ревью.
                не_туда = [н for н in вфайле if ч in тексты[н]]
                # Заголовок раздела назвал источник, а цитата нашлась
                # не в нём. Молчим, если абзац назвал свой документ и цитата
                # оттуда: раздел может законно цитировать соседа под явным
                # адресом. Молчим и если цитата всё-таки есть в документе
                # заголовка — иначе получалось «приписана std474, стоит
                # в std474».
                if (в_заголовке and не_туда
                        and not any(ч in тексты[н] for н in в_заголовке)
                        and not (в_абзаце
                                 and any(ч in тексты[н] for н in в_абзаце))):
                    найдено.append({
                        "файл": короткий_путь(путь),
                        "стандарты": в_заголовке,
                        "фрагмент": часть.strip(),
                        "чужой": не_туда[:3],
                        "перечень": False,
                        "адрес": True,
                    })
                    continue
                # Цитата может быть законной и не из системы стандартов:
                # набор цитирует руководство разработчика и методические
                # материалы, у которых номера std нет. Ругаться на них —
                # значит подменять находку отсутствием данных.
                if стог and ч in стог:
                    continue
                # Цитата не из ИТС, но названная и объяснённая
                # в `tools/quotes-outside-its.md`. Совпадение по вхождению
                # в обе стороны: набор мог привести фрагмент короче
                # записанного или разбить его переносом строки.
                if any(ч in р or р in ч for р in разрешено):
                    continue
                # Имя собственного раздела набора, приведённое как адрес,
                # а не как цитата. Совпадение целиком: вхождение пропустило бы
                # любую цитату, начинающуюся с тех же слов.
                if ч in свои:
                    continue
                # Перечень, схлопнутый загрузчиком: сходится, если снять
                # маркеры. Это оформление переноса, а не правка цитаты.
                # Смотрим и в названные документы, и в общий стог: цитата
                # из руководства разработчика номера не имеет, а перечни
                # там такие же.
                мягко = без_маркеров(ч)
                если_перечень = bool(мягко) and (
                    any(мягко in без_маркеров(тексты[н]) for н in где)
                    or (стог and мягко in без_маркеров(стог)))
                # может быть, фрагмент есть, но в другом стандарте — это тоже
                # находка, но её надо назвать иначе
                чужой = [н for н in тексты if ч in тексты[н]]
                найдено.append({
                    "файл": короткий_путь(путь),
                    "стандарты": где,
                    "фрагмент": часть.strip(),
                    "чужой": чужой[:3],
                    "перечень": bool(если_перечень),
                })
    return найдено


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--навык", help="проверить один навык, а не все")
    р.add_argument("--файл", nargs="+", metavar="ПУТЬ",
                   help="проверить названные markdown-файлы вместо навыков: "
                        "выписку, замысел раздела, отчёт о ревью")
    р.add_argument("--минимум", type=int, default=40,
                   help="не судить фрагменты короче стольких знаков (по умолчанию 40)")
    р.add_argument("--подробно", action="store_true")
    а = р.parse_args()

    тексты, стог = корпуса()
    разрешено = разрешённые()
    свои = заголовки_набора()
    if тексты is None:
        print("[предупреждение] корпуса ИТС не выгружены — сверка цитат "
              "не выполнялась")
        return 0

    # Названные файлы — вместо обхода навыков. Нужно для того, что навыком
    # ещё не стало: выписки, замыслы разделов, отчёты о ревью. Их цитаты
    # до сих пор не сверялись ничем, а именно в них цитата рождается —
    # и оттуда переезжает в навык уже правленой.
    if а.файл:
        пути = [п for п in а.файл if п.endswith(".md")]
        чужие = [п for п in а.файл if not п.endswith(".md")]
        if чужие:
            print("[предупреждение] не markdown, пропущены: %s"
                  % ", ".join(чужие))
    else:
        имена = [а.навык] if а.навык else sorted(
            и for и in os.listdir(НАВЫКИ)
            if os.path.isdir(os.path.join(НАВЫКИ, и)))
        пути = []
        for имя in имена:
            каталог = os.path.join(НАВЫКИ, имя)
            for корень, _, файлы in os.walk(каталог):
                пути += [os.path.join(корень, ф) for ф in sorted(файлы)
                         if ф.endswith(".md")]

    всего, находки = 0, []
    for путь in пути:
        if not os.path.isfile(путь):
            print("[предупреждение] нет файла: %s" % путь)
            continue
        всего += 1
        находки += проверить_файл(путь, тексты, стог, а.минимум, разрешено,
                                  свои)

    строгие = [н for н in находки
               if not н.get("перечень") and not н.get("адрес")]
    адресные = [н for н in находки if н.get("адрес")]
    перечни = [н for н in находки if н.get("перечень")]

    for н in строгие:
        адрес = (", ".join(подпись(s) for s in н["стандарты"])
                 if н["стандарты"] else "корпусах ИТС")
        print("[!] %s — цитата не найдена в %s" % (н["файл"], адрес))
        print("    «%s»" % (н["фрагмент"][:160]))
        if н["чужой"]:
            print("    но найдена в: %s" % ", ".join(подпись(s) for s in н["чужой"]))
        if а.подробно:
            print("    нормализованный вид: %s" % нормализовать(н["фрагмент"])[:160])

    for н in адресные:
        print("[адрес] %s — цитата приписана %s, а стоит в %s" %
              (н["файл"], ", ".join(подпись(s) for s in н["стандарты"]),
               ", ".join(подпись(s) for s in н["чужой"])))
        print("    «%s»" % (н["фрагмент"][:160]))

    if перечни:
        print("\n[разметка перечня] %d — сходятся после снятия маркеров: "
              "загрузчик корпуса схлопывает границу <li> в пробел, и перечень\n"
              "  приходит сплошной строкой. Это оформление переноса, "
              "не правка цитаты; в код возврата не идёт." % len(перечни))
        if а.подробно:
            for н in перечни:
                print("    %s: «%s»" % (н["файл"], н["фрагмент"][:100]))

    if адресные:
        print("\n[адрес] %d — заголовок раздела называет один документ, "
              "а цитата стоит в другом.\n"
              "  Класс читается человеком и в код возврата не идёт: у него "
              "есть законные срабатывания —\n"
              "  например, когда набор цитирует формулировку, чтобы сказать, "
              "что её в документе НЕТ." % len(адресные))

    print("\nфайлов проверено: %d, документов в корпусе: %d, "
          "цитат не сошлось: %d, адрес под вопросом: %d "
          "(плюс %d на разметке перечня)"
          % (всего, len(тексты), len(строгие), len(адресные), len(перечни)))
    return 1 if строгие else 0


if __name__ == "__main__":
    sys.exit(main())
