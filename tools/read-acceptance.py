"""Чтение журнала приёмки: ответы агентов из `run-acceptance.ps1` в один файл.

    python tools/read-acceptance.py D:/tmp/1c-acceptance/run1-kilo-9to20
    python tools/read-acceptance.py <каталог> --пара 9 --полярность Neg

Приёмку нельзя свести к числу. Скрипт `run-acceptance.ps1` пишет в journal
поле `questionsRaw` — счёт знаков «?» — и сам предупреждает, что мера это
негодная: вопросительный знак ловит тернарный оператор `?(Условие, Да, Нет)`
и `<?xml ?>`. На первом же прогоне 05.09.2026 так и вышло: у прошедшего Pos
стояло `questionsRaw = 1`, и единица была тернарным оператором внутри
выданного кода.

Поэтому прибор здесь не судит, а **достаёт текст**: ответ агента, список
поднятых навыков и признак загрузки — чтобы человек прочитал и решил.
Логи Kilo приходят в UTF-16 и JSON Lines по строке на событие; вручную
это не читается.

Что печатается по каждому прогону:

  * пара, полярность, среда;
  * поднялся ли навык и какие именно (поле `skills` журнала);
  * последний текстовый ответ агента целиком.

С `--кратко` печатается только шапка — так видно раскладку всего прогона
на одном экране.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

# Про эту преамбулу см. check-sources.py: перенаправленный вывод берёт ANSI
# системы, и первый же знак вне cp1251 роняет отчёт трассировкой.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass


def события(каталог):
    """Записи progress.jsonl. Файл пишется PowerShell-ом и идёт с BOM."""
    файл = Path(каталог) / "progress.jsonl"
    if not файл.is_file():
        raise SystemExit("нет журнала: %s" % файл)
    out = []
    for строка in файл.read_text(encoding="utf-8-sig").splitlines():
        строка = строка.strip()
        if строка.startswith("{"):
            out.append(json.loads(строка))
    return out


СБОЙ = "[СРЕДА СОРВАЛАСЬ]"

# Ссылка на источник в ответе агента: номер стандарта или адрес параграфа
# руководства. Это и есть признак того, что до ответа доехал набор, а не
# общее знание модели — своих номеров модель не выдумывает, а набор носит
# адрес при каждом утверждении.
#
# Образец широкий намеренно. Узкая редакция («стандарт NNN», «stdNNN»)
# не ловила форму «стандарт 1С № 686», которой агент написал в прогоне 4,
# — то есть прибор, которым меряется главное число этапа, занижал.
# Пересчёт обеими редакциями по 63 прогонам разошёлся ровно на одном,
# и главное число устояло; но образец с тех пор широкий.
ССЫЛКА = re.compile(
    r"(?:std\s*|стандарт[а-яё]{0,3}\s*(?:1[СC]\s*)?(?:№\s*)?)(\d{3})\b",
    re.IGNORECASE)
ПАРАГРАФ = re.compile(r"§\s?\d{1,2}\.\d")


def ссылки(текст):
    """Сколько разных ссылок на источник несёт ответ."""
    if not текст or текст.startswith(СБОЙ):
        return 0
    return len(set(ССЫЛКА.findall(текст))) + len(set(ПАРАГРАФ.findall(текст)))


ШУМ = re.compile(r"[*`«»\"']")
ДЛИНА_СЛЕДА = 45


def _норм(с):
    return " ".join(ШУМ.sub(" ", с).lower().split())


def _тексты_набора():
    """Все тексты набора одной нормализованной простынёй."""
    корень = Path(__file__).resolve().parent.parent / "skills"
    if not корень.is_dir():
        raise SystemExit("нет каталога skills/ — сверять ответ не с чем")
    return _норм("\n".join(п.read_text(encoding="utf-8")
                           for п in корень.rglob("*.md")))


_НАБОР = None


def след(текст, длина=ДЛИНА_СЛЕДА):
    """Самый длинный кусок ответа, дословно совпавший с текстом набора.

    Ссылка на номер стандарта показывает, что доехал **адрес**. Этот
    признак сильнее: он показывает, что доехала **формулировка** — модель
    воспроизвела фразу набора, а не пересказала общее знание.

    Первая редакция этой проверки была списком из восьми фраз, подобранных
    руками («Откатить копию можно», «ошибка не падает, а записывается»…),
    и дала Kilo 5, Claude 5, Codex 0. Вывод «Codex не несёт формулировок
    набора вовсе» продержался до первого честного замера: дословных кусков
    в 45 знаков и длиннее у Codex восемь из 23, у Kilo десять из 26,
    у Claude девятнадцать из 26. **Список подобранных руками маркеров —
    не измерение, а иллюстрация.**
    """
    global _НАБОР
    if not текст or текст.startswith(СБОЙ):
        return ""
    if _НАБОР is None:
        _НАБОР = _тексты_набора()
    о = _норм(текст)
    лучший = ""
    for i in range(0, max(0, len(о) - длина), 10):
        if о[i:i + длина] in _НАБОР:
            j = i + длина
            while j < len(о) and о[i:j + 1] in _НАБОР:
                j += 1
            if j - i > len(лучший):
                лучший = о[i:j]
    return лучший


def ответ(путь):
    """Последний текстовый ответ агента из run.log.

    Форматов два, и они разные. **Kilo**: строка на событие, текст лежит
    в `part.text` у частей типа `text`. **Claude Code**: строка на событие,
    но текст — внутри `message.content`, списком частей, где вперемешку
    `thinking`, `tool_use` и `text`.

    Разбирать надо оба, и вот почему это не мелочь. Прибор, знавший только
    формат Kilo, на журналах Claude Code возвращал пустоту — и сводка
    печатала «ссылок на источник: 0» по двадцати прогонам, где раздел
    поднялся. Читалось это как находка о среде («Claude не цитирует
    стандарты»), а было свойством прибора: вход до него не дошёл.
    Поймано 05.09.2026 на середине прогона 5 — сверкой с Kilo, где те же
    пары давали 28 ссылок.

    Берётся последняя текстовая часть: предыдущие — промежуточные
    рассуждения и вывод инструментов.
    """
    п = Path(путь)
    if not п.is_file():
        return None
    сырое = п.read_bytes()
    if сырое[:2] in (b"\xff\xfe", b"\xfe\xff"):
        текст = сырое.decode("utf-16")
    else:
        текст = сырое.decode("utf-8-sig", errors="replace")
    куски, сбой = [], None
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка.startswith("{"):
            continue
        try:
            о = json.loads(строка)
        except ValueError:
            continue
        # Среда падает молча для вызывающего: kilo.exe возвращает 0, скрипт
        # прогона пишет run-done, и прогон выглядит состоявшимся при пустом
        # ответе. Поймано 05.09.2026 на паре 15 Neg: 35 шагов, 37 вызовов
        # инструментов и «Invalid prompt: The messages do not match the
        # ModelMessage[] schema» в конце. Сорвавшийся прогон обязан быть
        # виден как сорвавшийся, а не как ответ длиной ноль.
        if о.get("type") == "error":
            данные = (о.get("error") or {}).get("data") or {}
            сбой = данные.get("message") or (о.get("error") or {}).get("name")
            continue
        часть = о.get("part") or {}
        if часть.get("type") == "text" and часть.get("text"):
            куски.append(часть["text"])
            continue
        # Claude Code: message.content — список частей, текст среди них.
        сообщение = о.get("message")
        if not isinstance(сообщение, dict):
            continue
        содержимое = сообщение.get("content")
        if isinstance(содержимое, str) and содержимое.strip():
            куски.append(содержимое)
        elif isinstance(содержимое, list):
            for ч in содержимое:
                if (isinstance(ч, dict) and ч.get("type") == "text"
                        and ч.get("text")):
                    куски.append(ч["text"])
    if not куски:
        # Codex пишет не JSON, а расшифровку разговора: строка-маркер
        # `codex` открывает ответ, строка `tokens used` его закрывает.
        # Прибор, знавший только JSON, на этих журналах молча возвращал
        # пустоту — четвёртый за сессию случай «ноль находок, потому что
        # вход не дошёл».
        строки = текст.splitlines()
        начала = [i for i, с in enumerate(строки) if с.strip() == "codex"]
        if начала:
            начало = начала[-1] + 1
            конец = len(строки)
            for i in range(начало, len(строки)):
                if строки[i].strip().startswith("tokens used"):
                    конец = i
                    break
            собрано = "\n".join(строки[начало:конец]).strip()
            if собрано:
                куски.append(собрано)
    if куски:
        return куски[-1]
    return (СБОЙ + " " + сбой) if сбой else None


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("каталог")
    р.add_argument("--пара", type=int, action="append")
    р.add_argument("--полярность", choices=["Pos", "Neg"])
    р.add_argument("--кратко", action="store_true")
    р.add_argument("--ссылки", action="store_true",
                   help="сводка: доезжают ли ссылки на источник без раздела")
    а = р.parse_args()

    прогонов = сорвалось = без_навыка = 0
    for о in события(а.каталог):
        вид = о.get("event")
        if вид not in ("run-done", "run-timeout", "run-error", "skip"):
            continue
        if а.пара and о.get("pair") not in а.пара:
            continue
        if а.полярность and о.get("pol") != а.полярность:
            continue
        шапка = "=== пара %-3s %-3s  %s" % (о.get("pair"), о.get("pol"),
                                            о.get("env"))
        if вид != "run-done":
            сорвалось += 1
            print(шапка + "  — %s %s" % (вид, о.get("reason", "")))
            continue
        т = ответ(о.get("log", ""))
        # Прогон, у которого среда упала, считается сорвавшимся, а не
        # состоявшимся: иначе сводка врёт в сторону благополучия — ровно
        # ту ошибку набор ловит у своих приборов третий раз.
        упал = bool(т) and т.startswith(СБОЙ)
        if упал:
            сорвалось += 1
            print(шапка + "  — среда сорвалась")
            if not а.кратко:
                print("    " + т[len(СБОЙ):].strip())
                print()
            continue
        прогонов += 1
        поднят = bool(о.get("skill"))
        if not поднят:
            без_навыка += 1
        print(шапка + "  навык: %s  [%s]"
              % ("да" if поднят else "НЕТ", о.get("skills") or "—"))
        if а.кратко:
            continue
        print(т if т else "    (ответа в журнале нет)")
        print()

    if а.ссылки:
        итог = {True: [0, 0, 0, 0], False: [0, 0, 0, 0]}
        for о in события(а.каталог):
            if о.get("event") != "run-done":
                continue
            if а.пара and о.get("pair") not in а.пара:
                continue
            if а.полярность and о.get("pol") != а.полярность:
                continue
            т = ответ(о.get("log", "")) or ""
            if т.startswith(СБОЙ):
                continue
            строка = итог[bool(о.get("skill"))]
            n = ссылки(т)
            строка[0] += 1
            строка[1] += 1 if n else 0
            строка[2] += n
            строка[3] += 1 if след(т) else 0
        print()
        print("%-22s %9s %9s %9s %10s"
              % ("", "прогонов", "со ссылк.", "ссылок", "с фразой"))
        for поднят, имя in ((True, "раздел поднялся"),
                            (False, "раздел не поднялся")):
            в, со, вс, фр = итог[поднят]
            print("%-22s %9d %9d %9d %10d" % (имя, в, со, вс, фр))
        print("«с фразой» — ответ содержит кусок текста набора в %d знаков "
              "и длиннее, дословно" % ДЛИНА_СЛЕДА)

    print("прогонов прочитано: %d, без поднятия навыка: %d, сорвалось: %d"
          % (прогонов, без_навыка, сорвалось))
    if not прогонов and not сорвалось:
        print("ВНИМАНИЕ: вход пуст — прибор ничего не смотрел, и ноль находок "
              "об этом не говорит")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
