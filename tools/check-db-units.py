"""Опись единиц с пометкой «БД»: где каждая стоит в наборе и какие без места.

    python tools/check-db-units.py                 # перепись целиком
    python tools/check-db-units.py --без-места     # только те, у кого места нет
    python tools/check-db-units.py --раздел 1c-queries

## Зачем

Этап УГЛУБЛЕНИЕ-БД разбирает 147 единиц решения 19 (`docs/closure.json`,
флаг `бд`). Первые четыре захода взяли те, что стоили дороже всего; пятый
берёт остальное. Чтобы не перечитывать набор заново на каждую единицу,
нужна опись: тема — файл, где она уже разобрана, либо пометка «места нет».

## Почему это перепись, а не приговор

Прибор **не решает**, закрыта тема или нет. Он раскладывает кандидатов
по убыванию совпадения и отделяет уверенные попадания от слабых. Судит
человек.

Чтобы «ничего не нашлось» нельзя было спутать с «прибор не дошёл», вывод
всегда называет числа: сколько единиц обработано, сколько получило место,
сколько файлов прочитано. Молчаливый ноль — тот самый дефект, который этот
набор ловит у чужих приборов.

## Мера совпадения, и почему первая редакция не годилась

Первая редакция считала долю основ названия, встретившихся в файле целиком.
На разделе `1c-queries` она дала 33 места из 33 при пороге в две трети —
то есть не различила ничего. Причина известна заранее: слово из названия
темы встречается в чужом разборе чаще, чем в своём, а в справочнике
на двадцать тысяч знаков найдётся почти любая основа.

Исправлено двумя поправками:

1. **Частые основы отброшены.** Основа, встречающаяся больше чем в четверти
   файлов набора, ничего не отбирает. Если у темы не осталось ни одной
   редкой основы, прибор говорит это прямо, а не выдаёт стопроцентное
   совпадение по служебным словам.
2. **Совпадение ищется внутри одного раздела файла, а не по всему файлу.**
   Файл режется по заголовкам; тема считается стоящей там, где её редкие
   основы сошлись в одном разделе. Две основы в разных концах справочника —
   не место темы.

Порог уверенности — две трети редких основ. Ниже него единица попадает
в список «проверить вручную», а не в «пробел»: разницу между «разобрано
под другим названием» и «не разобрано вовсе» прибор не знает.
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
ОПИСЬ = КОРЕНЬ / "docs" / "closure.json"
НАВЫКИ = КОРЕНЬ / "skills"
ОСНОВА = 6
ПОРОГ = 2 / 3

# Служебные слова названий тем: в разборе они есть везде и ничего не отбирают.
ШУМ = {
    "или", "как", "что", "это", "его", "они", "оно", "когда", "где", "чем",
    "том", "тем", "работе", "работы", "работа", "использование",
    "использования", "значений", "значения", "значение", "данных", "данные",
    "объектов", "объекта", "кода", "коде", "вместо", "также", "между",
}


def основы(текст):
    """Множество основ значимых слов. Короткие и служебные отброшены."""
    слова = re.findall(r"[а-яёa-z0-9]+", текст.lower())
    return {с[:ОСНОВА] for с in слова if len(с) >= 4 and с not in ШУМ}


def разделы_файла(текст):
    """[основы раздела] — файл режется по заголовкам markdown.

    Совпадение по файлу целиком не значит ничего: справочник большой,
    и основы темы находятся в нём порознь. Место темы — раздел, где они
    сошлись вместе.
    """
    куски = re.split(r"^#{1,6} ", текст, flags=re.M)
    return [основы(к) for к in куски if к.strip()]


def файлы_набора():
    """{путь от skills/: [основы каждого раздела]}."""
    склад = {}
    for п in sorted(НАВЫКИ.rglob("*.md")):
        склад[п.relative_to(НАВЫКИ).as_posix()] = разделы_файла(
            п.read_text(encoding="utf-8"))
    return склад


def частые(склад):
    """Основы, встречающиеся больше чем в четверти файлов: шум, не признак."""
    счёт = {}
    for разделы in склад.values():
        для_файла = set().union(*разделы) if разделы else set()
        for о in для_файла:
            счёт[о] = счёт.get(о, 0) + 1
    предел = max(1, len(склад) // 4)
    return {о for о, n in счёт.items() if n > предел}


def единицы_бд(раздел=None):
    d = json.loads(ОПИСЬ.read_text(encoding="utf-8"))
    итог = []
    for р in d["разделы"]:
        if раздел and р["раздел"] != раздел:
            continue
        for е in р["единицы"]:
            if е.get("бд"):
                итог.append((р["раздел"], е["что"], е.get("чем_закрывается", "")))
    return итог


def кандидаты(что, склад, свой_раздел, шум):
    """([(доля, путь)] по убыванию, редкие основы темы).

    Доля считается по лучшему разделу файла, а не по файлу целиком.
    """
    о = основы(что) - шум
    if not о:
        return [], о
    оценки = []
    for путь, разделы in склад.items():
        доля = max((len(о & р) / len(о) for р in разделы), default=0.0)
        if доля > 0:
            # Свой раздел весомее чужого: одинаковое слово в чужом разборе
            # встречается чаще, чем в своём, и без этого перевеса опись
            # раскладывает темы по соседям.
            оценки.append((доля + (0.001 if путь.startswith(свой_раздел + "/") else 0),
                           доля, путь))
    оценки.sort(reverse=True)
    return [(д, п) for _, д, п in оценки], о


def main(argv=None):
    разбор = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    разбор.add_argument("--раздел")
    разбор.add_argument("--без-места", action="store_true", dest="без_места",
                        help="печатать только единицы ниже порога уверенности")
    разбор.add_argument("--кандидатов", type=int, default=2)
    арг = разбор.parse_args(argv)

    склад = файлы_набора()
    список = единицы_бд(арг.раздел)
    if not список:
        raise SystemExit("[ошибка] ни одной единицы с пометкой «бд» не отобрано: "
                         "либо раздел назван неверно, либо изменился формат "
                         "docs/closure.json. Пустая опись — не результат.")

    шум = частые(склад)
    с_местом = слабых = безосновных = 0
    текущий = None
    for раздел, что, чем in список:
        к, редкие = кандидаты(что, склад, раздел, шум)
        нет_основ = not редкие
        уверенно = bool(к) and к[0][0] >= ПОРОГ and not нет_основ
        if нет_основ:
            безосновных += 1
        if уверенно:
            с_местом += 1
        else:
            слабых += 1
        if арг.без_места and уверенно:
            continue
        if раздел != текущий:
            print()
            print("=== %s" % раздел)
            текущий = раздел
        метка = "  " if уверенно else "??"
        print("%s %s  [%s]" % (метка, что, чем))
        if нет_основ:
            print("       редких основ в названии нет — судить по названию нечем")
            continue
        for доля, путь in к[:арг.кандидатов]:
            print("       %3d%%  %s" % (round(доля * 100), путь))
        if not к:
            print("       кандидатов нет вовсе")

    print()
    print("единиц с пометкой БД обработано: %d" % len(список))
    print("из них место найдено уверенно (>= %d%% редких основ): %d"
          % (round(ПОРОГ * 100), с_местом))
    print("ниже порога — проверить вручную: %d" % слабых)
    print("из них без редких основ в названии: %d" % безосновных)
    print("файлов набора прочитано: %d, частых основ отброшено: %d"
          % (len(склад), len(шум)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
