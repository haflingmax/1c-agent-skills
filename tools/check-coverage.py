"""Полнота навыка против подзаголовков руководства разработчика.

Шаг 6 конвейера спрашивает не «верно ли сказанное» (это шаг 4), а «есть ли
тема вообще». У этого вопроса, в отличие от предыдущего, есть машинный
признак: подзаголовок источника либо назван в навыке, либо нет.

    python tools/check-coverage.py --навык 1c-update-and-support --главы 36 37 38

**Счётчик печатает рассмотренное, а не только найденное.** Ноль находок
у прибора, до которого не дошёл вход, выглядит так же, как ноль находок
у полного покрытия; различает их только число на входе. Поэтому «под
вопросом: 0» без строки «подзаголовков рассмотрено» читать нельзя.

Чего этот прибор не умеет, и это не оговорка, а граница применения:

  * **соразмерность.** Тема считается покрытой, если её слова встречаются
    в навыке. Одна строчка и полный разбор для него одинаковы;
  * **методички и стандарты.** Сверка идёт по руководству разработчика:
    у `metod8dev` и `v8std` нумерованных подзаголовков такого вида нет;
  * **верность.** Названная тема может быть изложена неправильно — это
    вопрос шага 4, и его надо задавать отдельно.

Совпадение засчитывается двумя способами: по номеру параграфа («§37.2.5»)
или по значимым словам заголовка. Второй нужен потому, что навык часто
пересказывает тему, не называя номер, — и требовать номер значило бы
объявить дырой каждый такой пересказ.

## Когда его показаниям верить, а когда нет

Замерено 31.08.2026 прогоном по всем собранным разделам: 116 «дыр», и почти
все ложные. Настоящей оказалась одна — §30.4.19 у `1c-extensions`. Разница
не в приборе, а в том, что ему дали на вход, и различать это обязан
вызывающий:

  * **глава должна быть источником раздела один к одному.** У расширений
    глава 30 — ровно их глава, и находка настоящая. А `1c-build-and-db`
    против главы 35 дал 31 «дыру» — карту маршрута бизнес-процесса
    и HTML-редактор, которые разделу и не принадлежат. Прибор там мерил
    не полноту раздела, а разницу между объёмом главы и объёмом раздела;
  * **подзаголовки должны быть темами, а не словарём.** `1c-reports-and-layouts`
    против главы 10 дал 23 «дыры», и все 23 — отдельные функции языка
    компоновки: ВРЕГ, ГОД, ДЕНЬ, ПОДСТРОКА. Навык правильно их не перечисляет:
    это работа синтакс-помощника, а не правил. Там, где у главы подзаголовок
    на каждое слово языка, показания прибора не значат ничего.

Отсюда порядок: **сначала назвать главу, которая и есть источник раздела,
и только потом читать число.** Прогон «по всем главам подряд» даёт длинный
список, который выглядит как работа и ею не является.
"""
import argparse
import importlib.util
import os
import re
import sys
from pathlib import Path

# Про эту преамбулу см. check-sources.py: перенаправленный вывод берёт ANSI
# системы, и первый же знак вне cp1251 роняет отчёт трассировкой.
if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
НАВЫКИ = КОРЕНЬ / "skills"

# Подзаголовок руководства: «37.2.5. Права пользователя хранилища».
#
# Точки после номера мало: «Режим совместимости 8.3.10. Версия платформы» ей
# удовлетворяет, и номер версии уходил в счётчик рассмотренного наравне
# с параграфом — то есть прибор врал в ту сторону, в которую врать нельзя,
# завышая знаменатель. Поймано тестом, а не глазами. Поэтому ниже первая
# часть номера обязана совпасть с номером читаемой главы.
ЗАГОЛОВОК = re.compile(r"\b(\d{1,2}(?:\.\d+){1,4})\.\s+([А-ЯЁ][^\n.]{4,90})")

# Слово считается значимым от пяти букв: короткие («для», «при», «окно»)
# встречаются в любом тексте и засчитали бы покрытие кому угодно.
ЗНАЧИМОЕ = re.compile(r"[а-яёa-z]{5,}")


def руководство():
    """Главы руководства разработчика из выгрузки ИТС, ключ — номер главы."""
    поиск = КОРЕНЬ / "tools" / "its-search.py"
    спец = importlib.util.spec_from_file_location("its_search", поиск)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    главы = {}
    for заголовок, текст, _адрес in модуль.загрузить("devguide"):
        м = re.match(r"Глава (\d+)\.", заголовок)
        if м:
            главы[м.group(1)] = (заголовок, текст)
    return главы


def текст_навыка(имя):
    каталог = НАВЫКИ / имя
    if not каталог.is_dir():
        raise SystemExit("нет навыка: %s" % имя)
    return "\n".join(п.read_text(encoding="utf-8")
                     for п in sorted(каталог.rglob("*.md")))


def покрытие(навык, главы, интерес):
    """(рассмотрено, дыры). Дыра — (номер, заголовок, совпало, всего слов)."""
    сплошной = " ".join(навык.lower().split())
    рассмотрено, дыры, видели = 0, [], set()
    for номер_главы in sorted(главы, key=int):
        _заголовок, текст = главы[номер_главы]
        for м in ЗАГОЛОВОК.finditer(текст):
            номер, имя = м.group(1), " ".join(м.group(2).split())
            if номер.split(".")[0] != номер_главы:
                continue
            if not any(номер == п or номер.startswith(п + ".") for п in интерес):
                continue
            if номер in видели:
                continue
            видели.add(номер)
            рассмотрено += 1
            по_номеру = ("§" + номер) in навык or (номер + " ") in навык
            слова = ЗНАЧИМОЕ.findall(имя.lower())
            # Сравниваем по шести первым буквам: падежи и числа иначе
            # объявили бы дырой тему, названную в другом склонении.
            совпало = sum(1 for с in слова if с[:6] in сплошной)
            хватает = слова and совпало >= max(1, len(слова) - 1)
            if not (по_номеру or хватает):
                дыры.append((номер, имя, совпало, len(слова)))
    return рассмотрено, дыры


def main():
    р = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--навык", required=True)
    р.add_argument("--главы", nargs="+", required=True,
                   metavar="N",
                   help="номера глав или параграфов: 36 37 38 2.14 39.2")
    а = р.parse_args()

    главы = руководство()
    нужные = {}
    for п in а.главы:
        номер = п.split(".")[0]
        if номер not in главы:
            raise SystemExit("в выгрузке нет главы %s" % номер)
        нужные[номер] = главы[номер]

    навык = текст_навыка(а.навык)
    рассмотрено, дыры = покрытие(навык, нужные, а.главы)

    for номер, имя, совпало, всего in дыры:
        print("[?] %-12s %-58s слов совпало %d из %d"
              % (номер, имя[:58], совпало, всего))
    print("\nподзаголовков рассмотрено: %d, покрыто: %d, под вопросом: %d"
          % (рассмотрено, рассмотрено - len(дыры), len(дыры)))
    if not рассмотрено:
        print("ВНИМАНИЕ: вход пуст — прибор ничего не смотрел, и ноль находок "
              "об этом не говорит")
        return 2
    # Дыра — повод посмотреть человеком, а не отказ: параграф бывает законно
    # вне раздела. Код возврата красным не делаем.
    return 0


if __name__ == "__main__":
    sys.exit(main())
