"""Проверка командной строки 1С:Предприятия до её запуска.

Ловит то, что модель выдумывает чаще всего: несуществующий ключ, ключ не из того
режима, опцию не от той команды, отсутствие обязательного пакетного ключа и
заглушку вместо настоящего пути.

Останавливает работу только то, про что запуском показано, что платформа этого
не делает, — см. docs/evidence/2026-08-22-blocking-rules.md. Остальное уходит в
предупреждения: у них ненулевой смысл и нулевой код возврата. Чужой инструмент
(ibcmd, rac, ras) скрипт не судит вовсе.

Разбор имени ключа моделирует платформу, а не только двенадцать слитных
(/L, /P, /N, /O, /WSA и прочие) — но и не «самое длинное совпадение среди
ВСЕХ ключей»: такая формула сама оказалась неверна (Н-02, повторное ревью)
и заблокировала бы законный /PRoxy2024 (→ /Proxy длиннее, чем /P, но
платформа проверено запуском резолвит его в /P + значение «Roxy2024» —
та же ошибка аутентификации, что и у контрольного /Padmin123). Модель РАЗБОРА
(какой ключ платформа подставит): длинный ключ участвует в совпадении, только
если его аргумент по документации — «голое» позиционное значение
(`<имя файла>` и подобное, без именованных под-ключей); если нужен отдельный
именованный под-ключ (/Proxy: `-PSrv <адрес> -PPort <порт>`) или аргумента
нет вовсе (/NoProxy: пустой `arg`) — глued-хвост эту форму не удовлетворяет,
и платформа откатывается к короткому slitному ключу (/P, /N).

Разбор — не то же самое, что доверие к нему (Н-02, третий раунд ревью):
таких «не glued, но способных принять хвост» ключей около пятидесяти
(/S, /WS, /C, /ConfigurationRepositoryF и прочие), и для большинства из них
поведение платформы НЕ проверялось запуском. Обобщение «не glued →
блокировать» опровергнуто одним прогоном: /S<адрес> платформа разбирает
ВЕРНО (`/Snosuchhost9999:1541/nodb` дал ошибку только из-за
несуществующего хоста, не разбора). Поэтому блокируются только три ключа
из PROVEN_TAIL_MISPARSE, каждый подтверждён СВОИМ прогоном:
/DumpCfg → /DumpCfgToFile (выгрузка ушла не в тот файл, тихая порча),
/Out → /OutBase (лог ушёл не в тот файл, тихая порча),
/LoadCfg → /LoadCfgFromFile («Файл не обнаружен», отказ). Остальные ключи
этого семейства — предупреждение, честно говорящее «не проверялось».

Состав ключей взят из руководства администратора 8.3.27, приложение 7
(140 ключей), и лежит в cli-keys.json рядом с этим файлом.

    python scripts/check-1c-cli.py "1cv8 DESIGNER /F d:/base /LoadCfg new.cf /UpdateDBCfg"
    echo "<команда>" | python scripts/check-1c-cli.py

Код возврата 1 — есть [ошибка]; 0 — запускать можно, даже если есть [внимание].
Годится для CI и для вызова из навыка.
"""
