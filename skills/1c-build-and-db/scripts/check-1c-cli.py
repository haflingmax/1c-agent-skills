def split_args(line):
    """Разбирает строку с учётом кавычек, не ломаясь о пути с пробелами.

    Кавычки допустимы и В СЕРЕДИНЕ токена: /P"пароль с пробелом" —
    законная форма платформы. Прежняя регулярка `"[^"]*"|\S+` отделяла
    кавычки только у токена, который с них НАЧИНАЕТСЯ, и для /P"…"
    первым срабатывал \S+ — значение рвалось по пробелам на три
    аргумента. Пока разбор только печатали, это была косметика; с появлением
    обёртки run-1c.py это фактическая строка запуска, и платформа получала
    другой пароль. Найдено сплошным ревью 24.09.2026.
    """
    аргументы = []
    текущий = ""
    в_кавычках = False
    есть = False
    for знак in line:
        if знак == '"':
            в_кавычках = not в_кавычках
            текущий += знак
            есть = True
        elif знак.isspace() and not в_кавычках:
            if есть:
                аргументы.append(текущий)
            текущий = ""
            есть = False
        else:
            текущий += знак
            есть = True
    if есть:
        аргументы.append(текущий)
    return аргументы


def absorbs_glued_tail(info):
    """Может ли ключ принять хвост токена как своё значение (glued или нет).

    Н-02, повторное ревью: «самое длинное совпадение среди ВСЕХ ключей» —
    неверная модель, заблокировала бы законный /PRoxy2024 (см. модуль
    docstring). Настоящий критерий — форма документированного аргумента
    ключа (`arg` в cli-keys.json), а не наличие признака glued:

    - `glued=True` (/L, /P, /N, /O и восемь других) — по определению берёт
      значение слитно. Участвует всегда.
    - `glued=False`, но `arg` начинается с «голого» `<значение>» без
      именованного под-ключа (/LoadCfg: `<имя cf/cfe файла> [...]`;
      /DumpCfg — так же; /Out: `<имя файла> [-NoTruncate]`; но и /S:
      `<адрес>`, /WS: `<url>` и ещё десятки других) — платформа способна
      принять остаток токена ЗА это значение. Участвует в совпадении. Но
      это НЕ означает, что подстановка проверенно неверна: третий раунд
      ревью (Н-02) нашёл, что /S<адрес> платформа разбирает ВЕРНО
      (`/Snosuchhost9999:1541/nodb` дал отказ только из-за
      несуществующего хоста). Эта функция отвечает только «участвует ли
      ключ в совпадении», а не «можно ли доверять результату» — решение
      о блокировке принимает check() по PROVEN_TAIL_MISPARSE, где
      доказанных запуском случаев ровно три: /LoadCfg, /DumpCfg, /Out.
    - `glued=False` и `arg` требует именованный под-ключ первым делом
      (/Proxy: `-PSrv <адрес> -PPort <порт> ...`) или вовсе пуст (/NoProxy:
      `""`) — глued-хвост эту форму не удовлетворяет, ключ НЕ участвует.
      Проверено запуском дважды: /PRoxy2024 после /N Admin даёт код 1,
      «Пользователь ИБ не идентифицирован» — ровно ту же ошибку, что и
      контрольный /Padmin123, то есть платформа взяла /P, а не /Proxy;
      /NoProxyUser даёт ту же ошибку — платформа взяла /N (у /NoProxy arg
      пуст, ему нечем принять «User»). И отдельно: /Proxy с настоящими
      -PSrv/-PPort прошёл штатно, код 0 — ключ не сломан, он просто не
      достижим слитным хвостом.
    """
    if info.get("glued"):
        return True
    arg = (info.get("arg") or "").strip()
    return arg.startswith("<")


def known_key(name, keys):
    """Возвращает каноническое имя ключа или None.

    Регистр не важен: платформа регистронезависима, проверено запуском —
    /dumpcfg отработал и создал файл.

    Совпадение по префиксу ищется среди ключей, которые способны принять
    хвост как значение (см. absorbs_glued_tail) — это не только двенадцать
    glued, но и не любой ключ каталога: /Proxy и /NoProxy в этот список не
    входят, хотя оба длиннее /P и /N (см. docstring модуля, Н-02).

    Среди подходящих кандидатов берётся самое длинное совпадение, а не
    первое: /O и /OIDA оба подходят /OIDAOff, и результат обязан быть
    /OIDA, а не /O; /LoadCfg длиннее /L и оба подходят /LoadCfgFromFile —
    результат /LoadCfg.

    Совпадение по префиксу — не то же самое, что точное, и не то же самое,
    что доказанно неверный разбор. Здесь возвращается только имя; решение —
    предупреждать или блокировать — check() принимает отдельно, по
    PROVEN_TAIL_MISPARSE (доказано запуском) и признаку glued (легитимное
    слитное значение), а не по одному лишь факту «резолвилось не в себя».
    """
    low = name.lower()
    for k in keys:
        if k.lower() == low:
            return k
    candidates = [k for k, info in keys.items()
                  if absorbs_glued_tail(info) and len(low) > len(k) and low.startswith(k.lower())]
    return max(candidates, key=len) if candidates else None


def matches_option(arg, option):
    """Опция совпадает точно либо со значением, приклеенным без пробела.

    В документации такие записаны как -Dynamic<Режим>, а на деле пишутся
    -Dynamic- и -Dynamic+. Приклеенное значение не может быть буквенным,
    иначе -Extensions прошло бы за -Extension.
    """
    a, o = arg.lower(), option.lower()
    if a == o:
        return True
    if a.startswith(o):
        tail = arg[len(option):]
        return bool(tail) and not tail[0].isalpha()
    return False


def _канон(арг, keys):
    """Каноническое имя ключа для аргумента, с учётом слитной формы.

    Зовёт known_key — ту самую модель разбора, которая уже описана
    в шапке модуля и проверена запуском. Своя вторая модель здесь была
    и разошлась с ней: она требовала, чтобы за ключом не стояла буква,
    и потому не узнавала ни /NАдмин, ни /Fd:/base. Прибор противоречил
    сам себе в одном отчёте — «команда без /N» рядом с «/NАдмин разобран
    как /N». Найдено сплошным ревью ветки 24.09.2026.
    """
    имя = арг.strip('"')
    if not имя.startswith("/"):
        return None
    return known_key(имя, keys)


def файловая_база(args, keys):
    """Путь из /F, если он есть.

    /S — клиент-серверная база, на диске её нет, и искать там нечего:
    проверка существования к ней неприменима и обязана молчать.
    """
    for i, a in enumerate(args):
        if _канон(a, keys) != "/F":
            continue
        имя = a.strip('"')
        if len(имя) > 2:
            return имя[2:].strip('"')
        if i + 1 < len(args):
            return args[i + 1].strip('"')
    return None


def есть_аутентификация(args, keys):
    """Задан ли /N. Пароль не проверяется: пустой /P"" — законная форма."""
    return any(_канон(a, keys) == "/N" for a in args)


def версия_формата(args):
    """Версия формата выгрузки из Configuration.xml, если путь к ней указан.

    Формат старше релиза платформы загружается, новее — нет. Сам релиз
    прибору неизвестен, поэтому он называет то, что видит, и отсылает
    к таблице соответствия: постмортем 28.08.2026 показал, что сверку
    делают после полутора часов вместо тридцати секунд до запуска.
    """
    for i, a in enumerate(args):
        if a.strip('"').upper() == "/LOADCONFIGFROMFILES" and i + 1 < len(args):
            cfg = Path(args[i + 1].strip('"')) / "Configuration.xml"
            if cfg.is_file():
                голова = cfg.read_text(encoding="utf-8", errors="replace")[:4000]
                # Объявление XML отбрасывается: в нём своё version="1.0",
                # и первая редакция возвращала его вместо версии формата.
                # Поймано тестом, а не глазами.
                голова = re.sub(r"<\?xml[^>]*\?>", "", голова, count=1)
                m = re.search(r'version="([\d.]+)"', голова)
                return m.group(1) if m else None
    return None


def check(line, catalog, ответы=frozenset()):
    """Разбор строки плюс три корзины фактов.

    `ответы` — то, что прибор знать не может и что назвал владелец:
    «пользователей-нет», «база-одноразовая», «копия-сделана». Параметр
    со значением по умолчанию: 43 прежних теста зовут check(line, catalog).
    """
    keys = catalog["ключи"]
    args = split_args(line)
    problems = []
    notes = []

    if not args:
        return ["%s пустая команда" % K_EMPTY_COMMAND], []

    tool = Path(args[0].strip('"')).name.lower()
    if not tool.startswith("1cv8"):
        # Не приговор команде, а граница компетенции: замечание с кодом возврата 0.
        # Иначе проверяльщик запрещал бы ibcmd, который рекомендует наш же рецепт
        # (references/load-configuration.md, шаг 3).
        return [], ["%s %s вне компетенции проверяльщика: он знает только команды 1cv8. "
                    "Состав ключей ibcmd, rac и ras сверяется по документации вручную"
                    % (K_FOREIGN_TOOL, args[0])]

    # I-6. Раздел 7.3.11 (процитирован ниже дословно): «Во время обработки
    # командной строки, содержимое файла полностью заменит собой командную
    # строку запускаемого приложения», и отсюда «команда /@ должна быть первой
    # или единственной командой командной строки». Значит при /@ первым ключом
    # режим, база и пакетный флаг лежат В ФАЙЛЕ, а не в строке — требовать их
    # в самой строке нельзя. Раньше документированная команда «1cv8 /@ файл»
    # блокировалась двумя ошибками сразу (K002 и K007) и получала код 1:
    # новая блокировка законного, ровно того рода, который Global Constraints
    # плана называет Critical.
    #
    # Имя первого ключа приводится к каноническому тем же known_key, что и
    # ниже: слитная запись «/@d:/cmd.txt» — тоже /@ первым ключом.
    first_key = next((a for a in args[1:] if a.startswith("/")), None)
    at_replaces_line = False
    if first_key is not None:
        at_replaces_line = known_key(first_key.split(":", 1)[0], keys) == "/@"

    mode = None
    for a in args[1:4]:
        up = a.upper()
        if up in MODE_WORDS:
            mode = up
            break
    if mode is None and not at_replaces_line:
        problems.append(
            "%s не указан режим запуска: после имени программы ожидается "
            "DESIGNER, ENTERPRISE или CREATEINFOBASE" % K_NO_MODE)

    used = []
    for i, a in enumerate(args):
        if not a.startswith("/"):
            continue
        name = a.split(":", 1)[0]
        canon = known_key(name, keys)
        if canon is None:
            problems.append("%s %s — такого ключа нет в документации 8.3.27" % (K_UNKNOWN_KEY, a))
            continue
        if canon.lower() == name.lower():
            used.append((canon, i))
            continue
        # Разрешено префиксом, а не точным совпадением — Н-02: платформа
        # берёт самое длинное совпадение среди ключей, способных принять
        # хвост (absorbs_glued_tail). Это отвечает только на вопрос «как
        # платформа РАЗБЕРЁТ строку». Отдельный вопрос — можно ли ДОВЕРЯТЬ
        # этому разбору, и на него отвечает не признак glued сам по себе,
        # а PROVEN_TAIL_MISPARSE: третий раунд ревью нашёл, что «не glued
        # → блокировать» была слишком широким обобщением (см. комментарий
        # у PROVEN_TAIL_MISPARSE) — /S<адрес> тоже не glued, но платформа
        # разбирает его верно.
        tail = name[len(canon):]
        if canon in PROVEN_TAIL_MISPARSE:
            # Доказанно неверно — не used.append: это не легитимное
            # использование ключа, а разбор, который сам проверенно
            # приводит не туда или в отказ. Правило 11 требует блокировки.
            problems.append(
                "%s %s — такого ключа нет в документации 8.3.27; платформа "
                "разберёт совпадение как %s с хвостом «%s», отправленным "
                "не в значение ключа, а в позиционный аргумент — проверено "
                "%s" % (K_PROVEN_MISPARSE, a, canon, tail, PROVEN_TAIL_MISPARSE[canon]))
        elif keys[canon].get("glued"):
            # Хвост — легитимное слитное значение (/Lru = /L + «ru»).
            # Молча пропускать нельзя: так же устроены и выдуманные
            # /Publish, /NewConfiguration, /OptimizeDatabase,
            # /WSAuthentication — тоже начинаются с glued-ключа. Блокировать
            # нельзя: /Lru и /Padmin работают (проверено запуском: /Lru +
            # /DumpCfg создал файл). Остаётся назвать сомнение вслух, с
            # нулевым кодом возврата.
            used.append((canon, i))
            notes.append(
                "%s %s — точно такого ключа в документации 8.3.27 нет; разобран "
                "как %s со значением «%s». Если имелся в виду другой ключ, "
                "он выдуман" % (K_GLUED_GUESS, a, canon, tail))
        else:
            # Не glued, и своего прогона для этого конкретного ключа нет
            # (третий раунд ревью, Н-02: /S<адрес> и ещё около полутора
            # десятков ключей — платформа проверенно разбирает /S верно,
            # остальные не проверялись вовсе). Нельзя ни молчать (может
            # оказаться выдумкой), ни блокировать (нет своего прогона,
            # доказавшего отказ, — а один прогон уже опроверг такое
            # обобщение). Честный текст без слов «проверено запуском» там,
            # где не проверено.
            used.append((canon, i))
            notes.append(
                "%s %s — точно такого ключа в документации 8.3.27 нет; разобран "
                "как %s с хвостом «%s» в значении. Поведение платформы для "
                "этого конкретного совпадения запуском не проверялось "
                "(проверено только для %s) — может оказаться и штатной "
                "работой (как /Lru), и тихой порчей результата (как "
                "/DumpCfgToFile); прежде чем полагаться на эту команду, "
                "стоит проверить запуском" % (
                    K_UNPROVEN_TAIL, a, canon, tail, ", ".join(sorted(PROVEN_TAIL_MISPARSE))))

    if used and any(n == "/@" for n, _ in used) and used[0][0] != "/@":
        # Раздел 7.3.11: «Команда /@ должна быть первой или единственной
        # командой командной строки запуска приложения. Если команда /@
        # указана не первой ‑ поведение является неопределенным.» «Неопределено»
        # — не «запрещено»: платформа не гарантированно откажет, поэтому
        # это предупреждение, а не блокировка (правило 11: блокировать
        # можно только доказанно неверное, а это не проверено запуском).
        notes.append(
            "%s /@ указан не первым ключом — раздел 7.3.11 руководства "
            "администратора называет поведение в этом случае неопределённым "
            "(содержимое файла должно было заменить собой всю командную "
            "строку целиком)" % K_AT_NOT_FIRST)

    for name, _ in used:
        # modes — список: ключ, документированный в нескольких разделах
        # (например /DumpResult — в 7.2.3 и 7.4.17), несёт оба. Пустой
        # список — «общий»: ключ не ограничен по режиму вовсе.
        restricted = [m for m in (keys[name].get("modes") or []) if m in MODE_WORDS]
        if not (mode and restricted and mode not in restricted):
            continue
        where = "%s работает в режиме %s, а команда запущена как %s" % (
            name, "/".join(restricted), mode)
        if "DESIGNER" in restricted:
            # Проверено запуском: ENTERPRISE /F <база> /LoadCfg <файл> не грузит
            # ничего — платформа открывает сеанс и не возвращает управление
            # (убит по таймауту 60 с), журнал пуст, /DumpResult не создан.
            problems.append("%s %s: пакетную операцию конфигуратора вне режима "
                             "DESIGNER выполнять некому — платформа открывает "
                             "сеанс и не завершается" % (K_WRONG_MODE_BLOCK, where))
        else:
            # Обратное направление запуском опровергнуто: DESIGNER /F <база>
            # /UsePrivilegedMode /DumpCfg отработал, файл создан и совпал по
            # размеру с обычной выгрузкой. Блокировать работающее нельзя.
            notes.append("%s %s; в пакетном запуске платформа такой ключ приняла "
                         "и операцию выполнила — проверь, нужен ли он здесь" % (K_WRONG_MODE_NOTE, where))

    # опции принадлежат ближайшему предшествующему ключу
    owners = {i: name for name, i in used}
    current = None
    for i, a in enumerate(args):
        if i in owners:
            current = owners[i]
            continue
        if not a.startswith("-") or len(a) < 2 or a[1].isdigit():
            continue
        if current is None:
            notes.append("%s %s — опция указана до первого ключа" % (K_OPT_BEFORE_KEY, a))
            continue
        allowed = keys[current].get("opts") or []
        if allowed and not any(matches_option(a, o) for o in allowed):
            near = [o for o in allowed if o.lower().startswith(a.lower()[:5])]
            hint = (", возможно " + near[0]) if near else ""
            # Не запрет: проверено запуском, что чужая опция команду не ломает —
            # DESIGNER /F <база> /DumpCfg <файл> -Format Hierarchical отработал,
            # файл создан и побайтно того же размера, что и без опции.
            notes.append("%s %s не является опцией %s%s" % (K_UNKNOWN_OPT, a, current, hint))

    # заглушки ищем по всей строке: <каталог базы> разрезается пробелом на два слова
    for pat, why in PLACEHOLDERS:
        m = pat.search(line)
        if m:
            problems.append("%s «%s» — %s; значение запрашивается у человека, "
                            "а не выдумывается" % (K_PLACEHOLDER, m.group(0), why))

    names = {n for n, _ in used}

    # at_replaces_line — см. I-6 выше: «1cv8 DESIGNER /@ файл» несёт
    # /DisableStartupDialogs внутри файла, требовать его в строке нельзя.
    if mode == "DESIGNER" and names and BATCH_REQUIRED not in names and not at_replaces_line:
        notes.append(
            "%s нет %s — пакетный запуск откроет диалог и остановится" % (K_NO_BATCH_FLAG, BATCH_REQUIRED))

    if names & DESTRUCTIVE and "/Out" not in names and "/DumpResult" not in names:
        notes.append(
            "%s нет /Out и /DumpResult — при сбое не останется ни журнала, ни кода возврата" % K_NO_OUT_OR_RESULT)

    if "/UpdateDBCfg" in names and not any(a.lower().startswith("-dynamic") for a in args):
        notes.append(
            "%s /UpdateDBCfg без -Dynamic: решение о динамическом обновлении "
            "принимается заранее, а не оставляется платформе" % K_UPDATEDBCFG_STATIC)

    # Сверяемся с каноническими именами из used, а не с началом строки: иначе
    # /f строчными и /IBConnectionString считаются незаданной базой. Блокировка
    # доказана запуском: DESIGNER /DumpCfg <файл> без базы даёт код 1,
    # «Неопределена информационная база», файла нет.
    if not (names & BASE_KEYS) and mode != "CREATEINFOBASE" and not at_replaces_line:
        problems.append(
            "%s не задана база: нужен /F, /S, /IBName или /IBConnectionString" % K_NO_BASE)

    # Корзина «увидел сам»: то, что проверяется с диска без платформы.
    # До 24.09.2026 проверяльщик разбирал только строку, и команда,
    # указывающая в несуществующую базу, проходила с кодом 0 — падала уже
    # платформа, на открытии базы, и это выглядело как беда платформы.
    путь = файловая_база(args, keys)
    существует = False
    if путь is not None:
        p = Path(путь)
        существует = p.is_dir() and (p / "1Cv8.1CD").is_file()
        if not существует:
            # Замечание, а не отказ, и это по спеке: корзина «увидел сам»
            # называет, отказывают корзины «знать не может» и «решение
            # владельца». Практическая цена ошибки здесь высока: тела навыков
            # показывают команды с иллюстративными путями (d:/base), и отказ
            # по несуществующей базе заблокировал бы 34 собственных примера
            # набора — сторож test_no_command_from_skill_bodies_is_blocked
            # поймал это в тот же час.
            notes.append(
                "%s база по пути %s не найдена: нет ни каталога с 1Cv8.1CD, "
                "ни файла базы. Если путь настоящий — команда запустится "
                "и упадёт на открытии базы, а не на разборе строки"
                % (K_BASE_MISSING, путь))

    if существует:
        # Корзина «знать не может». Список пользователей лежит внутри
        # 1Cv8.1CD, и любой способ его прочитать сам требует аутентификации.
        # Прибор не угадывает ответ — он отказывается пропускать вопрос молча.
        # Только для пакетного запуска. У интерактивного (открыть базу
        # в предприятии или конфигураторе) диалог авторизации — штатная
        # часть работы, а не зависание, и довод корзины к нему неприменим.
        # Ложный отказ здесь нашло сплошное ревью ветки 24.09.2026.
        пакетный = BATCH_REQUIRED in names
        if (пакетный and not есть_аутентификация(args, keys)
                and "пользователей-нет" not in ответы):
            problems.append(
                "%s пакетная команда без /N. Есть ли в базе пользователи, прибор "
                "знать не может: список лежит внутри 1Cv8.1CD, и любой способ "
                "его прочитать сам требует аутентификации. Если пользователь "
                "есть хотя бы один, платформа покажет модальный диалог, "
                "до которого пакетный процесс не дотянется: процесс будет жив, "
                "вывод пуст, файл базы не изменится — это выглядит как "
                "зависание, а не как отказ. Добавить /N и /P либо подтвердить: "
                "--ответ пользователей-нет" % K_AUTH_UNKNOWN)

        # Корзина «решение владельца». Правило SKILL.md:99 — «если ответа нет,
        # спроси, а не выбирай сам» — перенесено из прозы в прибор.
        размер = (p / "1Cv8.1CD").stat().st_size
        # DESTRUCTIVE — то же множество, что сторожит K015: одно понятие
        # «операция меняет базу необратимо» живёт в одном месте.
        необратимо = bool(names & DESTRUCTIVE)
        if размер > 0 and необратимо and not ({"база-одноразовая", "копия-сделана"} & set(ответы)):
            problems.append(
                "%s база непустая (%d байт), а операция меняет её необратимо. "
                "Рабочая она или одноразовая — решение владельца, а не догадка "
                "агента: от него зависит, нужна ли копия 1Cv8.1CD перед "
                "загрузкой. Ответить: --ответ база-одноразовая либо "
                "--ответ копия-сделана" % (K_OWNER_DECISION, размер))

    вер = версия_формата(args)
    if вер:
        notes.append(
            "%s версия формата выгрузки %s. Релиз платформы прибору неизвестен: "
            "формат старше релиза загружается, новее — нет. Сверить с "
            "references/xml-dump-format.md" % (K_DUMP_FORMAT, вер))

    return problems, notes


def main():
    argv = sys.argv[1:]
    if argv and argv[0] in ("-h", "--help"):
        # М-25: без этого argv[0] == "--help" уходил дальше как обычная
        # команда для проверки — tool.startswith("1cv8") давал False, и
        # скрипт молча отвечал «--help вне компетенции проверяльщика»
        # вместо помощи.
        print(__doc__.strip())
        return 0
    ответы = set()
    остаток = []
    i = 0
    while i < len(argv):
        if argv[i] == "--ответ" and i + 1 < len(argv):
            ответы.add(argv[i + 1])
            i += 2
            continue
        остаток.append(argv[i])
        i += 1
    argv = остаток

    line = " ".join(argv).strip()
    if not line:
        line = sys.stdin.read().strip()
    if not line:
        print(__doc__.strip().splitlines()[0])
        return 2

    problems, notes = check(line, load_catalog(), ответы)

    for p in problems:
        print(format_diag("ошибка", p))
    for n in notes:
        print(format_diag("внимание", n))
    if not problems and not notes:
        print("замечаний нет")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
