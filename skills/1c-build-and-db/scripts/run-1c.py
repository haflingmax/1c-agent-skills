"""Запуск команды платформы через проверку, с ожиданием и диагнозом зависания.

    python scripts/run-1c.py "1cv8 DESIGNER /F d:/base /N Админ /P\"\" /LoadCfg new.cf /UpdateDBCfg -Dynamic- /DisableStartupDialogs /Out log.txt"
    python scripts/run-1c.py --ответ база-одноразовая "1cv8 DESIGNER /F d:/base /N Admin /P\"\" /LoadCfg new.cf /UpdateDBCfg -Dynamic- /DisableStartupDialogs /Out log.txt"

Код возврата: 2 — команда не прошла проверку и не запускалась; 3 — истекло
время ожидания (в отчёте диагноз); иначе — код возврата самой платформы.

## Зачем

Голый запуск `1cv8` — худший из доступных способов, и это не мнение.

Во-первых, `1cv8.exe` собран как оконное приложение и возвращает управление
немедленно (references/load-configuration.md). Запущенный обычным образом,
он не создаст ни файлов, ни журнала, ни кода возврата — и это выглядит
в точности как тихий отказ.

Во-вторых, команду надо было проверить, а это отдельный шаг, который
пропускают: постмортем 28.08.2026 описывает полтора часа в цикле молчаливых
отказов, где проверяльщик не запускали ни разу, хотя он отказал бы на первой
же команде.

Обёртка делает оба шага одним и добавляет третий — диагноз зависанию.
Она не дисциплина, а выгода: короче и полезнее, чем запуск по памяти.
Дисциплина без выгоды проигрывает лени всегда.
"""
import argparse
import importlib.util
import re
import os
import subprocess
import sys
import time
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass


def _проверяльщик():
    """check-1c-cli.py как модуль. Имя файла с дефисом не импортируется обычным
    import, поэтому загружается по пути — рядом, в том же каталоге навыка."""
    сп = importlib.util.spec_from_file_location(
        "check_1c_cli_for_run", ЗДЕСЬ / "check-1c-cli.py")
    м = importlib.util.module_from_spec(сп)
    сп.loader.exec_module(м)
    return м


def _без_кавычек(арг):
    """Снимает ровно одну пару обрамляющих кавычек."""
    if len(арг) >= 2 and арг[0] == '"' and арг[-1] == '"':
        return арг[1:-1]
    return арг


def _подготовить_аргументы(аргументы):
    """Приводит аргументы к тому виду, в каком их понимает платформа.

    Кавычки внутри ОТДЕЛЬНОГО аргумента не нужны и вредны: границу
    значения задаёт сам аргумент, а `subprocess` на Windows собирает
    строку через `list2cmdline`, который экранирует внутреннюю кавычку
    как \\". Платформа получает `/F\\"D:/база\\"` и падает на пути.

    Проверено запуском 25.09.2026 на живой базе:

        /F"D:/1C/base/trade"  -> код 1, «Неправильный путь к файлу»
        /FD:/1C/base/trade    -> код 0, «Сохранение конфигурации успешно»
        /F + "D:/1C base/x"   -> путь с пробелом доезжает целым

    Пустое значение в кавычках разворачивается в отдельный пустой
    аргумент, а не выбрасывается: `/P""` означает пустой пароль, и просто
    убрав кавычки, прибор скормил бы платформе следующий ключ вместо
    пароля. Проверено там же: `/P` с пустым аргументом даёт код 0,
    слитное `/P""` — «Пользователь ИБ не идентифицирован».
    """
    готово = []
    for а in аргументы:
        а = _без_кавычек(а)
        пустое = re.match(r'^(/[A-Za-zА-Яа-я@]+)""$', а)
        if пустое:
            готово.append(пустое.group(1))
            готово.append("")
            continue
        готово.append(а.replace('"', ''))
    return готово


def _отпечаток(база):
    """(время правки, размер) файла базы — или None, если базы нет.

    Постмортем 28.08.2026: «если 1Cv8.1CD LastWriteTime не изменился после
    операции — операция не прошла». Отпечаток снимается до запуска, чтобы
    было с чем сравнить.
    """
    if not база:
        return None
    ф = Path(база) / "1Cv8.1CD"
    if not ф.is_file():
        return None
    с = ф.stat()
    return (с.st_mtime, с.st_size)


def _диагноз(база, было, вывод):
    стало = _отпечаток(база)
    if not вывод and было is not None and было == стало:
        return ("[диагноз] процесс не завершился, вывод пуст, 1Cv8.1CD не менялся. "
                "Это не медленная операция: платформа показывает модальный диалог "
                "авторизации, до которого пакетный процесс не дотягивается. "
                "Не ждать дольше — добавить /N и /P либо запустить вручную.")
    return ("[диагноз] истекло время ожидания, но признаков модального диалога нет: "
            "либо был вывод, либо файл базы менялся. Операция шла — "
            "увеличить --таймаут или проверить журнал /Out.")


def запустить(команда, ответы=frozenset(), таймаут=3600, порог_подозрения=45):
    """(код возврата, отчёт). Код 2 — отказ проверки, запуск не состоялся.

    `команда` — список аргументов (предпочтительно) либо строка. Список
    надёжнее в любой оболочке: закавычить ОТДЕЛЬНЫЙ аргумент умеет каждая,
    а строку с кавычками внутри не сохраняет одинаково ни одна. PowerShell
    5.1, например, съедает внутренние кавычки при вызове нативной
    программы — на этом встал живой прогон 25.09.2026, и модель, дважды
    получив usage, написала свой запускатель.

    `порог_подозрения` — через сколько секунд молчания напечатать диагноз,
    не дожидаясь конца ожидания. Без этого диагноз был недостижим на
    практике: инструмент `bash` у агента убивает процесс по своему
    таймауту, обычно задолго до часа, и отчёт, печатаемый в конце,
    не печатался никогда.
    """
    м = _проверяльщик()
    каталог = м.load_catalog()
    если_список = not isinstance(команда, str)
    # Список уходит в проверяльщик списком, а не склеенной строкой: склейка
    # воссоздала бы двусмысленность, ради устранения которой список
    # и заводится, и прибор отвечал бы «вне компетенции» на пути с пробелом.
    беды, замечания = м.check(команда, каталог, ответы)
    строки = [м.format_diag("ошибка", b) for b in беды]
    строки += [м.format_diag("внимание", z) for z in замечания]
    if беды:
        строки.append("запуск не выполнялся: команда не прошла проверку")
        return 2, "\n".join(строки)

    if если_список:
        аргументы = _подготовить_аргументы(команда)
    else:
        # Парные кавычки снимаются: split_args держит «/F "d:/1C базы"» одним
        # аргументом, но кавычки в нём оставляет, и программа получила бы их
        # как часть имени. Это работа оболочки, и в строковой форме делать
        # её приходится здесь.
        аргументы = _подготовить_аргументы(м.split_args(команда))
    база = м.файловая_база(аргументы, каталог["ключи"])
    было = _отпечаток(база)
    начало = time.time()
    процесс = subprocess.Popen(аргументы,
                               stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT)
    # Диагноз печатается сразу, как только признаки сошлись, а не в конце
    # ожидания: до конца обёртка может не дожить. Печать — не в отчёт,
    # а прямо в поток, с немедленным сбросом.
    сказано = False
    вывод = b""
    while True:
        осталось = таймаут - (time.time() - начало)
        if осталось <= 0:
            процесс.kill()
            вывод, _ = процесс.communicate()
            строки.append(_диагноз(база, было, вывод))
            return 3, "\n".join(строки)
        try:
            вывод, _ = процесс.communicate(timeout=min(порог_подозрения, осталось))
            break
        except subprocess.TimeoutExpired:
            if not сказано and _отпечаток(база) == было:
                print(_диагноз(база, было, b""), flush=True)
                сказано = True

    код = процесс.returncode
    строки.append("время: %.1f с, код возврата: %d" % (time.time() - начало, код))
    стало = _отпечаток(база)
    if было is not None and было == стало:
        строки.append(
            "[внимание] 1Cv8.1CD не изменился. Если операция должна была "
            "менять базу — она не прошла, и причину надо искать во входе "
            "(команда, аутентификация, формат файлов), а не в журнале.")
    if вывод:
        строки.append(вывод.decode("utf-8", errors="replace").strip())
    return код, "\n".join(строки)


ПОДСКАЗКА = """
Команду надёжнее передавать списком аргументов после --, а не одной строкой:

    python run-1c.py --ответ база-одноразовая -- \\
      "C:/Program Files/1cv8/8.3.27.2325/bin/1cv8.exe" DESIGNER \\
      /F "D:/1C/base/trade" /N Администратор /P "" \\
      /LoadConfigFromFiles "D:/src" /UpdateDBCfg -Dynamic- \\
      /DisableStartupDialogs /Out "D:/logs/load.txt"

Закавычить ОТДЕЛЬНЫЙ аргумент умеет любая оболочка. Строку с кавычками
внутри не сохраняет одинаково ни одна: PowerShell 5.1 съедает внутренние
кавычки при вызове нативной программы, и путь с пробелом разрывается.

Внутри отдельного аргумента кавычки НЕ нужны: границу значения задаёт
сам аргумент. Писать /F"D:/база" одним аргументом не надо — обёртка такие
кавычки уберёт, но лучше их и не ставить. Пустое значение — это ДВА
аргумента: /P и пустая строка, а не слитное /P"".

Строковая форма тоже принимается — одним аргументом, в одинарных кавычках
в PowerShell и bash:

    python run-1c.py --ответ база-одноразовая '1cv8 DESIGNER /F d:/base /N Админ /P"" /DumpCfg out.cf /DisableStartupDialogs /Out log.txt'
"""


def main(argv=None):
    р = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        epilog=ПОДСКАЗКА,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    р.add_argument("--ответ", action="append", default=[],
                   help="пользователей-нет | база-одноразовая | копия-сделана")
    р.add_argument("--таймаут", type=int, default=3600,
                   help="секунд ожидания процесса, по умолчанию час")
    р.add_argument("команда", nargs=argparse.REMAINDER,
                   help="программа и её ключи (после --), либо вся строка одним "
                        "аргументом")
    а = р.parse_args(argv)

    части = [ч for ч in а.команда if ч != "--"] if а.команда else []
    if not части:
        # Отказ обязан учить правильному вызову: в живом прогоне 25.09.2026
        # модель дважды получила голый usage и на третий раз написала свой
        # запускатель. Прибор, не показавший верную форму, толкает обходить
        # себя.
        print("не указана команда." + ПОДСКАЗКА)
        return 2

    команда = части[0] if len(части) == 1 else части
    код, отчёт = запустить(команда, set(а.ответ), а.таймаут)
    print(отчёт)
    return код


if __name__ == "__main__":
    sys.exit(main())
