"""Запуск команды платформы через проверку, с ожиданием и диагнозом зависания.

    python scripts/run-1c.py --пустой-пароль -- 1cv8 DESIGNER /F d:/base /N Админ /LoadCfg new.cf /UpdateDBCfg -Dynamic- /DisableStartupDialogs /Out log.txt
    python scripts/run-1c.py --ответ база-одноразовая --пустой-пароль -- 1cv8 DESIGNER /F d:/base /N Admin /LoadCfg new.cf /UpdateDBCfg -Dynamic- /DisableStartupDialogs /Out log.txt

Код возврата: 2 — команда не прошла проверку и не запускалась; 3 — истекло
время ожидания (в отчёте диагноз); иначе — код возврата самой платформы.

## Зачем

Голый запуск `1cv8` — худший из доступных способов, и это не мнение.

Во-первых, `1cv8.exe` собран как оконное приложение и возвращает управление
немедленно (references/load-configuration.md). Запущенный обычным образом,
он не создаст ни файлов, ни журнала, ни кода возврата — и это выглядит
в точности как тихий отказ.

Во-вторых, команду надо было проверить, а это отдельный шаг, который
пропускают: постмортем 28.08.2026 описывает полтора часа в цикле молчаливых
отказов, где проверяльщик не запускали ни разу, хотя он отказал бы на первой
же команде.

Обёртка делает оба шага одним и добавляет третий — диагноз зависанию.
Она не дисциплина, а выгода: короче и полезнее, чем запуск по памяти.
Дисциплина без выгоды проигрывает лени всегда.
"""
import argparse
import importlib.util
import re
import os
import subprocess
import sys
import time
from pathlib import Path

ЗДЕСЬ = Path(__file__).resolve().parent
_КЛЮЧИ = None
_МОДУЛЬ = None

if not os.environ.get("PYTHONIOENCODING"):
    for _поток in (sys.stdout, sys.stderr):
        try:
            _поток.reconfigure(encoding="utf-8", errors=_поток.errors)
        except (AttributeError, ValueError):
            pass


def _проверяльщик():
    """check-1c-cli.py как модуль. Имя файла с дефисом не импортируется обычным
    import, поэтому загружается по пути — рядом, в том же каталоге навыка."""
    global _МОДУЛЬ
    if _МОДУЛЬ is None:
        сп = importlib.util.spec_from_file_location(
            "check_1c_cli_for_run", ЗДЕСЬ / "check-1c-cli.py")
        _МОДУЛЬ = importlib.util.module_from_spec(сп)
        сп.loader.exec_module(_МОДУЛЬ)
    return _МОДУЛЬ


def _без_кавычек(арг):
    """Снимает ровно одну пару обрамляющих кавычек."""
    if len(арг) >= 2 and арг[0] == '"' and арг[-1] == '"':
        return арг[1:-1]
    return арг


def _подготовить_аргументы(аргументы):
    """Приводит аргументы к тому виду, в каком их понимает платформа.

    Кавычки внутри ОТДЕЛЬНОГО аргумента не нужны и вредны: границу
    значения задаёт сам аргумент, а `subprocess` на Windows собирает
    строку через `list2cmdline`, который экранирует внутреннюю кавычку
    как \\". Платформа получает `/F\\"D:/база\\"` и падает на пути.

    Проверено запуском 25.09.2026 на живой базе:

        /F"D:/1C/base/trade"  -> код 1, «Неправильный путь к файлу»
        /FD:/1C/base/trade    -> код 0, «Сохранение конфигурации успешно»
        /F + "D:/1C base/x"   -> путь с пробелом доезжает целым

    Пустое значение в кавычках разворачивается в отдельный пустой
    аргумент, а не выбрасывается: `/P""` означает пустой пароль, и просто
    убрав кавычки, прибор скормил бы платформе следующий ключ вместо
    пароля. Проверено там же: `/P` с пустым аргументом даёт код 0,
    слитное `/P""` — «Пользователь ИБ не идентифицирован».

    Это работает, только если пустой аргумент вообще доехал. В PowerShell
    5.1 он не доезжает никогда: оболочка выбрасывает его молча, и сюда
    приходит уже голый `/P`. Поэтому пустой пароль задаётся флагом
    `--пустой-пароль`, который дорисовывает пару внутри Python, а не
    написанием пары руками — см. _дописать_пустой_пароль.
    """
    готово = []
    for а in аргументы:
        а = _без_кавычек(а)
        пустое = re.match(r'^(/[A-Za-zА-Яа-я@]+)""$', а)
        if пустое:
            готово.append(пустое.group(1))
            готово.append("")
            continue
        готово.append(а.replace('"', ''))
    return готово


def _дописать_пустой_пароль(аргументы):
    """Добавляет пару /P и пустую строку, если пароля в команде ещё нет.

    Пустой аргумент невыразим в PowerShell 5.1: при вызове нативной
    программы он молча выбрасывается. Проверено печатью sys.argv
    25.09.2026 — «/P ""» доезжает как голый «/P», и платформа берёт
    за пароль следующий ключ. Доказательство того, что это не мелочь:
    в живом прогоне так вышло «Неопределена информационная база»,
    и модель повторила тот же запуск восемь раз.

    Флаг без значения съесть нечем, и пара собирается уже здесь, внутри
    Python, — на этом участке оболочки между командой и платформой нет.
    Правило общее для любой среды: ни Windows, ни POSIX это место
    не касается.
    """
    if any(_канон_ключа(а) == "/P" for а in аргументы):
        return аргументы
    return list(аргументы) + ["/P", ""]


def _канон_ключа(арг):
    """Имя ключа аргумента, с учётом слитного значения. None — не ключ.

    Зовёт ту же модель разбора, что и проверяльщик, вместо своей второй:
    у набора уже был случай, когда вторая модель разошлась с первой и
    прибор противоречил сам себе в одном отчёте.
    """
    имя = арг.strip('"')
    if not имя.startswith("/"):
        return None
    global _КЛЮЧИ
    if _КЛЮЧИ is None:
        # Каталог читается один раз на запуск, а не на каждый аргумент:
        # иначе разбор семнадцати аргументов означал бы семнадцать
        # загрузок модуля проверяльщика и семнадцать разборов каталога.
        _КЛЮЧИ = _проверяльщик().load_catalog()["ключи"]
    return _проверяльщик().known_key(имя.split(":", 1)[0], _КЛЮЧИ)


def _отпечаток(база):
    """(время правки, размер) файла базы — или None, если базы нет.

    Постмортем 28.08.2026: «если 1Cv8.1CD LastWriteTime не изменился после
    операции — операция не прошла». Отпечаток снимается до запуска, чтобы
    было с чем сравнить.
    """
    if not база:
        return None
    ф = Path(база) / "1Cv8.1CD"
    if not ф.is_file():
        return None
    с = ф.stat()
    return (с.st_mtime, с.st_size)


def _потомки_windows(корень):
    """pid процесса и всех его потомков — снимком списка процессов Windows."""
    import ctypes
    from ctypes import wintypes

    class PROCESSENTRY32W(ctypes.Structure):
        _fields_ = [("dwSize", wintypes.DWORD), ("cntUsage", wintypes.DWORD),
                    ("th32ProcessID", wintypes.DWORD),
                    ("th32DefaultHeapID", ctypes.c_size_t),
                    ("th32ModuleID", wintypes.DWORD), ("cntThreads", wintypes.DWORD),
                    ("th32ParentProcessID", wintypes.DWORD),
                    ("pcPriClassBase", ctypes.c_long), ("dwFlags", wintypes.DWORD),
                    ("szExeFile", ctypes.c_wchar * 260)]

    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    k32.CreateToolhelp32Snapshot.restype = wintypes.HANDLE
    k32.CreateToolhelp32Snapshot.argtypes = [wintypes.DWORD, wintypes.DWORD]
    k32.Process32FirstW.argtypes = [wintypes.HANDLE, ctypes.POINTER(PROCESSENTRY32W)]
    k32.Process32NextW.argtypes = [wintypes.HANDLE, ctypes.POINTER(PROCESSENTRY32W)]
    k32.CloseHandle.argtypes = [wintypes.HANDLE]
    снимок = k32.CreateToolhelp32Snapshot(0x2, 0)  # TH32CS_SNAPPROCESS
    if not снимок or снимок == ctypes.c_void_p(-1).value:
        return [корень]
    родитель = {}
    try:
        з = PROCESSENTRY32W()
        з.dwSize = ctypes.sizeof(PROCESSENTRY32W)
        ок = k32.Process32FirstW(снимок, ctypes.byref(з))
        while ок:
            родитель[з.th32ProcessID] = з.th32ParentProcessID
            ок = k32.Process32NextW(снимок, ctypes.byref(з))
    finally:
        k32.CloseHandle(снимок)
    return _замкнуть(корень, родитель)


def _потомки_linux(корень):
    родитель = {}
    for имя in os.listdir("/proc"):
        if not имя.isdigit():
            continue
        try:
            with open("/proc/%s/stat" % имя, "rb") as ф:
                поля = ф.read().rsplit(b")", 1)[1].split()
            родитель[int(имя)] = int(поля[1])
        except (OSError, IndexError, ValueError):
            continue
    return _замкнуть(корень, родитель)


def _замкнуть(корень, родитель):
    """Корень и все, чей предок по цепочке — корень. Корень идёт первым."""
    свои = [корень]
    прирост = True
    while прирост:
        прирост = False
        for pid, ppid in родитель.items():
            if ppid in свои and pid not in свои and pid != ppid:
                свои.append(pid)
                прирост = True
    return свои


def _время_одного_windows(pid):
    import ctypes
    from ctypes import wintypes
    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    k32.OpenProcess.restype = wintypes.HANDLE
    k32.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
    k32.CloseHandle.argtypes = [wintypes.HANDLE]
    h = k32.OpenProcess(0x1000, False, pid)  # PROCESS_QUERY_LIMITED_INFORMATION
    if not h:
        return None
    try:
        c, e, ядро, польз = (wintypes.FILETIME() for _ in range(4))
        if not k32.GetProcessTimes(wintypes.HANDLE(h), ctypes.byref(c), ctypes.byref(e),
                                   ctypes.byref(ядро), ctypes.byref(польз)):
            return None

        def сек(ft):
            return ((ft.dwHighDateTime << 32) | ft.dwLowDateTime) / 1e7
        return сек(ядро) + сек(польз)
    finally:
        k32.CloseHandle(h)


def _время_одного_linux(pid):
    try:
        with open("/proc/%d/stat" % pid, "rb") as ф:
            поля = ф.read().rsplit(b")", 1)[1].split()
        return (int(поля[11]) + int(поля[12])) / os.sysconf("SC_CLK_TCK")
    except (OSError, IndexError, ValueError):
        return None


def _процессорное_время(pid):
    """Суммарное процессорное время процесса и его потомков, в секундах.

    None — в этой ОС снять не умеем (не Windows и не Linux) либо процесса
    уже нет. Потомки считаются потому, что на Linux платформу нередко
    запускают через сценарий-обёртку, и тогда работу делает не сам pid.

    Только стандартная библиотека: набор не тянет зависимостей, а psutil
    на машине агента может и не стоять.
    """
    try:
        if os.name == "nt":
            pids, одно = _потомки_windows(pid), _время_одного_windows
        elif sys.platform.startswith("linux"):
            pids, одно = _потомки_linux(pid), _время_одного_linux
        else:
            return None
        замеры = [одно(p) for p in pids]
        if замеры[0] is None:
            return None
        return sum(з for з in замеры if з is not None)
    except Exception:
        # Измерение — подсказка, а не условие запуска: сбой в нём
        # не должен ронять саму операцию над базой.
        return None


# Меньше этого за интервал наблюдения — процесс ждёт, а не работает.
# Спящий процесс набирает сотые доли секунды; живая /DumpConfigToFiles
# набирала от 1,5 до 8 с процессорного времени за 10 с (замер 25.09.2026).
ПОРОГ_РАБОТЫ = 0.5


def _диагноз(прирост, интервал, окончательно):
    """Текст диагноза по приросту процессорного времени за интервал.

    Прежний признак — «вывод пуст и 1Cv8.1CD не менялся» — ложен для
    любой долгой операции и опровергнут запуском 25.09.2026: выгрузка
    шла (74 с процессорного времени, 4000 файлов), а обёртка печатала
    «модальный диалог… Не ждать дольше», и по этой подсказке агент убил
    загрузку конфигурации на третьей минуте. /Out платформа пишет в конце,
    а время правки открытого на запись файла Windows обновляет не сразу —
    оба признака молчат у работающего процесса точно так же, как у висящего.
    """
    if прирост is None:
        return ("[наблюдение] процесс жив и молчит %d с. Отличить работу от "
                "ожидания в этой ОС прибор не умеет. Не прерывать раньше "
                "--таймаут; занятость процессора смотреть средствами ОС."
                % интервал)
    if прирост >= ПОРОГ_РАБОТЫ:
        if окончательно:
            return ("[диагноз] истекло время ожидания, а процесс РАБОТАЛ: +%.1f с "
                    "процессорного времени за последние %d с. Это не зависание, "
                    "операции просто не хватило времени — повторить с большим "
                    "--таймаут. Загрузка XML-выгрузки в десятки гигабайт идёт "
                    "десятки минут." % (прирост, интервал))
        return ("[идёт работа] процесс работает: +%.1f с процессорного времени "
                "за %d с. Молчание — норма: /Out платформа пишет в конце. "
                "Это не зависание, не прерывать." % (прирост, интервал))
    return ("[диагноз] процесс жив, но процессор не занят: +%.2f с за %d с. "
            "Он ждёт, а не работает. Частая причина — модальный диалог "
            "(вход, вопрос платформы), до которого пакетный процесс не "
            "дотягивается; без /DisableStartupDialogs это вероятнее всего. "
            "Проверить вход (/N, /P) и что базу не держит другой сеанс."
            % (прирост, интервал))


def запустить(команда, ответы=frozenset(), таймаут=3600, порог_подозрения=45,
              пустой_пароль=False):
    """(код возврата, отчёт). Код 2 — отказ проверки, запуск не состоялся.

    `команда` — список аргументов (предпочтительно) либо строка. Список
    надёжнее в любой оболочке: закавычить ОТДЕЛЬНЫЙ аргумент умеет каждая,
    а строку с кавычками внутри не сохраняет одинаково ни одна. PowerShell
    5.1, например, съедает внутренние кавычки при вызове нативной
    программы — на этом встал живой прогон 25.09.2026, и модель, дважды
    получив usage, написала свой запускатель.

    `порог_подозрения` — через сколько секунд молчания напечатать диагноз,
    не дожидаясь конца ожидания. Без этого диагноз был недостижим на
    практике: инструмент `bash` у агента убивает процесс по своему
    таймауту, обычно задолго до часа, и отчёт, печатаемый в конце,
    не печатался никогда.
    """
    м = _проверяльщик()
    каталог = м.load_catalog()
    если_список = not isinstance(команда, str)
    if пустой_пароль:
        # Пара дорисовывается ДО проверки, а не после: проверяльщик обязан
        # видеть ту же команду, что уйдёт в платформу, иначе его отчёт
        # описывает не то, что запущено.
        команда = _дописать_пустой_пароль(
            list(команда) if если_список else м.split_args(команда))
        если_список = True
    # Список уходит в проверяльщик списком, а не склеенной строкой: склейка
    # воссоздала бы двусмысленность, ради устранения которой список
    # и заводится, и прибор отвечал бы «вне компетенции» на пути с пробелом.
    беды, замечания = м.check(команда, каталог, ответы)
    строки = [м.format_diag("ошибка", b) for b in беды]
    строки += [м.format_diag("внимание", z) for z in замечания]
    if беды:
        строки.append("запуск не выполнялся: команда не прошла проверку")
        return 2, "\n".join(строки)

    if если_список:
        аргументы = _подготовить_аргументы(команда)
    else:
        # Парные кавычки снимаются: split_args держит «/F "d:/1C базы"» одним
        # аргументом, но кавычки в нём оставляет, и программа получила бы их
        # как часть имени. Это работа оболочки, и в строковой форме делать
        # её приходится здесь.
        аргументы = _подготовить_аргументы(м.split_args(команда))
    база = м.файловая_база(аргументы, каталог["ключи"])
    было = _отпечаток(база)
    начало = time.time()
    процесс = subprocess.Popen(аргументы,
                               stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT)
    # Наблюдение печатается на каждом интервале, а не в конце ожидания:
    # до конца обёртка может не дожить — инструмент агента убивает её
    # по своему таймауту. Печать — прямо в поток, с немедленным сбросом.
    вывод = b""
    прежнее = _процессорное_время(процесс.pid)
    отметка = time.time()
    while True:
        осталось = таймаут - (time.time() - начало)
        if осталось <= 0:
            сейчас = _процессорное_время(процесс.pid)
            прирост = (сейчас - прежнее
                       if сейчас is not None and прежнее is not None else None)
            процесс.kill()
            вывод, _ = процесс.communicate()
            строки.append(_диагноз(прирост, time.time() - отметка, True))
            return 3, "\n".join(строки)
        try:
            вывод, _ = процесс.communicate(timeout=min(порог_подозрения, осталось))
            break
        except subprocess.TimeoutExpired:
            сейчас = _процессорное_время(процесс.pid)
            прирост = (сейчас - прежнее
                       if сейчас is not None and прежнее is not None else None)
            if таймаут - (time.time() - начало) > 0:
                print(_диагноз(прирост, time.time() - отметка, False), flush=True)
                if сейчас is not None:
                    прежнее, отметка = сейчас, time.time()

    код = процесс.returncode
    строки.append("время: %.1f с, код возврата: %d" % (time.time() - начало, код))
    стало = _отпечаток(база)
    if было is not None and было == стало:
        строки.append(
            "[внимание] 1Cv8.1CD не изменился. Если операция должна была "
            "менять базу — она не прошла, и причину надо искать во входе "
            "(команда, аутентификация, формат файлов), а не в журнале.")
    if вывод:
        строки.append(вывод.decode("utf-8", errors="replace").strip())
    return код, "\n".join(строки)


