def test_без_корпуса_это_предупреждение(tmp_path):
    """Отсутствие выгрузки — не нарушение набора, и падать на нём нельзя."""
    р = subprocess.run([sys.executable, СКРИПТ, "--навык", "нет-такого"],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", cwd=str(tmp_path))
    # вне репозитория корпуса нет; код возврата обязан быть нулевым
    assert р.returncode == 0, р.stdout + р.stderr
