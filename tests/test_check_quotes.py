# -*- coding: utf-8 -*-
"""Проверки сверки цитат с корпусом ИТС.

Инструмент нужен потому, что четыре круга опровержения подряд не нашли того,
что он находит за секунды: правку внутри кавычек. Агенты сверяют смысл,
а добавленная запятая, просклонённое слово и съеденное многоточием «кроме»
смысла почти не меняют — они меняют то, что набор объявил дословным.

Проверяется здесь не «находит ли», а два свойства, без которых инструмент
вреден: он не ругается на законное (разметка, экранирование, цитаты
из корпусов без номера стандарта) и не молчит на подделке.
"""
import importlib.util
import os
import subprocess
import sys

import pytest

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СКРИПТ = os.path.join(КОРЕНЬ, "tools", "check-quotes.py")
КОРПУС = os.path.join(КОРЕНЬ, "_its", "v8std-full.json")


def модуль():
    спец = importlib.util.spec_from_file_location("check_quotes", СКРИПТ)
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м


@pytest.fixture(scope="module")
def cq():
    return модуль()


# ---------- нормализация: не ругаться на законное ----------

@pytest.mark.parametrize("разметка,источник", [
    ("**жирный** текст", "жирный текст"),
    ("`ПравоДоступа` вызывают", "ПравоДоступа вызывают"),
    ("> цитата блоком\n> вторая строка", "цитата блоком вторая строка"),
    ("звёздочка \\* экранирована", "звездочка * экранирована"),
    ("ёлка и ель", "елка и ель"),
    ("тире — разное – совсем", "тире - разное - совсем"),
    ("«ёлочки» и „лапки“", "елочки и лапки"),
    ("десятков**)", "десятков)"),
    ("права**, следует", "права, следует"),
])
def test_нормализация_не_создаёт_расхождений(cq, разметка, источник):
    """Разметка навыка не должна отличать цитату от источника."""
    assert cq.нормализовать(разметка) == cq.нормализовать(источник)


def test_нормализация_сохраняет_правку_слова(cq):
    """Главное свойство: то, ради чего инструмент и написан.

    Если нормализация «размоет» падеж или съеденное слово, инструмент станет
    бесполезным — он обязан различать эти пары.
    """
    пары = [
        ("повысить устойчивость кода", "ради устойчивости кода"),
        ("кроме проверки наличия роли (или какого-то права) при реализации",
         "кроме проверки наличия роли (или какого-то права), при реализации"),
        ("предоставлять эту роль всем категориям",
         "предоставлять всем категориям"),
        ("вставив в начало процедуры", "вставить в начало процедуры"),
        ("относящиеся к разным библиотекам не могут",
         "относящиеся к разным библиотекам, не могут"),
    ]
    for источник, правка in пары:
        assert cq.нормализовать(источник) != cq.нормализовать(правка), (
            "нормализация стёрла правку: %r и %r сошлись" % (источник, правка))


# ---------- разбор ссылок на стандарты ----------

@pytest.mark.parametrize("текст,ожидаем", [
    ("по std724 пункт 5", {"724"}),
    ("стандарт 488, пункт 2", {"488"}),
    ("стандарта 689 и стандартом 532", {"689", "532"}),
    ("## Константы (689, пункты 5.1–5.4)", {"689"}),
    ("**488** «Стандартные роли»", {"488"}),
    ("вычет (`std487`, `std629`)", {"487", "629"}),
    ("в 2026 году вышло 300 статей", set()),
])
def test_номера_узнаются_во_всех_принятых_формах(cq, текст, ожидаем):
    """Набор ссылается на стандарт четырьмя способами, и все должны читаться.

    Ошибка здесь не безобидна: не узнанный номер означает, что цитата
    сверяется не с тем документом либо не сверяется вовсе.
    """
    assert cq.номера(текст) == ожидаем


def test_голое_число_не_считается_ссылкой(cq):
    """Иначе «периодичность 300 секунд» превратится в ссылку на std300."""
    assert cq.номера("периодичность 300 секунд") == set()


# ---------- поведение на подделке и на законном ----------

@pytest.mark.skipif(not os.path.isfile(КОРПУС), reason="корпус ИТС не выгружен")
def test_подделанная_цитата_находится(tmp_path, cq):
    """Слово, вставленное внутрь кавычек, обязано быть найдено."""
    тексты, стог = cq.корпуса()
    навык = tmp_path / "skills" / "проба"
    навык.mkdir(parents=True)
    (навык / "SKILL.md").write_text(
        "По стандарту 724 сказано: «Не следует изменять данные,\n"
        "полученные из кэша **немедленно**. В противном случае, возможны\n"
        "скрытые ошибки в работе программы».\n", encoding="utf-8")

    найдено = cq.проверить_файл(str(навык / "SKILL.md"), тексты, стог, 40)
    assert найдено, "подделка внутри кавычек не найдена"


