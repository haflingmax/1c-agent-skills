# ---------- маркер перечня в выгрузке ИТС ----------

def test_маркер_выгрузки_снимается(cq):
    """Выгрузка ИТС размечает перечни знаком «●» (U+25CF).

    Первая редакция `без_маркеров` снимала «•» и «·», которых в корпусе нет,
    и мягкий класс «разметка перечня» не срабатывал ни разу — перечни
    из руководства уходили в строгие находки.
    """
    assert cq.без_маркеров("а ● б") == "а б"


# ---------- склейка составного имени, разорванного переносом ----------

def test_склейка_имени_работает(cq):
    """«ХранилищеНастроек.\nЗагрузить» — одно имя, разорванное переносом."""
    assert "хранилищенастроек.загрузить" in cq.нормализовать(
        "ХранилищеСистемныхНастроек.\nЗагрузить()".replace(
            "ХранилищеСистемныхНастроек", "ХранилищеНастроек"))


def test_склейка_не_трогает_границу_предложения(cq):
    """«…данных. Диаграмма Ганта» — два предложения, а не составное имя.

    Правило обещало «CamelCase с обеих сторон», а проверяло только правую
    и склеивало любую точку перед заглавной. Из-за этого цитата расходилась
    с источником там, где в корпусе на той же границе стоит маркер перечня.
    """
    assert ". диаграмма" in cq.нормализовать("компоновки данных. Диаграмма Ганта")


