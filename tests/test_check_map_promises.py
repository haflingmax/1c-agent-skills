"""Проверка сверки карты глав: ловит ли она пустое обещание.

Приёмка здесь именная. Главы 20, 23 и 32 были розданы картой и не написаны
четыре месяца; глава 29 — 204 тыс. знаков — пролежала так же и не была
названа ни одним списком отсутствий. Прибор полноты все четыре считал
покрытыми. Поэтому первый тест — про строку карты, обещающую «целиком»
там, где следов главы нет ни одного.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location(
    "check_map_promises", КОРЕНЬ / "tools" / "check-map-promises.py")
мод = importlib.util.module_from_spec(спец)
sys.modules["check_map_promises"] = мод
спец.loader.exec_module(мод)

ТАБЛИЦА = """Какой-то текст перед картой.

| Глава руководства | Раздел навыка | Что взято |
|---|---|---|
| 20 Полнотекстовый поиск | `1c-queries` | целиком |
| 29 Система взаимодействия | `1c-integrations` | **только `std798`**, механизм не разобран |
| 24 Механизм разделения данных, 25 История данных | `1c-metadata-objects` | **ничего** |
| 11 Бухгалтерский учет | `1c-metadata-objects` | целиком |
| 30 Расширения | `1c-extensions` | целиком |
| 22 Журнал регистрации | `1c-publish-and-operate` | целиком |

Текст после карты.
"""


def test_строки_разбираются_включая_две_главы_в_одной_ячейке():
    строки = мод.строки_карты(ТАБЛИЦА)
    assert len(строки) == 6
    главы = [г for г, _н, _о in строки]
    assert ["24", "25"] in главы, (
        "в одной ячейке карты стоят две главы, и обе обязаны попасть в счёт")


def test_разделительная_строка_таблицы_не_считается_обещанием():
    assert all(г != ["---"] for г, _н, _о in мод.строки_карты(ТАБЛИЦА))


def test_карта_кончается_на_первой_строке_без_трубы():
    строки = мод.строки_карты(ТАБЛИЦА + "\n| 99 Чужая таблица | `x` | y |\n")
    assert len(строки) == 6, (
        "таблица кончается пустой строкой; всё, что идёт после текста, "
        "к карте не относится")


def test_обещание_целиком_без_следов_главы_это_нарушение(monkeypatch):
    monkeypatch.setattr(мод, "следы", lambda глава, навык: 0)
    виды = [в for в, *_ in мод.проверить(мод.строки_карты(ТАБЛИЦА))]
    assert виды.count("пустое обещание") == 4, (
        "четыре строки обещают «целиком»; при нуле следов все четыре — дыры")
    assert "оговорка устарела" not in виды, (
        "строки с оговоркой при нуле следов правдивы и молчать обязан прибор")


def test_оговорка_при_обильных_следах_устарела(monkeypatch):
    monkeypatch.setattr(мод, "следы", lambda глава, навык: 17)
    находки = мод.проверить(мод.строки_карты(ТАБЛИЦА))
    виды = [в for в, *_ in находки]
    assert виды.count("оговорка устарела") == 3, (
        "глава 29 и две главы в третьей строке несут оговорку; следы "
        "означают, что оговорка отстала от содержимого")
    assert "пустое обещание" not in виды


def test_несуществующий_раздел_в_карте_виден_отдельным_видом():
    таблица = ТАБЛИЦА.replace("`1c-queries`", "`1c-nonexistent`")
    виды = [в for в, *_ in мод.проверить(мод.строки_карты(таблица))]
    assert "нет такого раздела" in виды, (
        "карта, указывающая на несуществующий раздел, — переадресация "
        "в пустоту; это отдельный класс дефекта набора")


def test_пара_считается_по_разделу_а_не_по_главе(monkeypatch):
    """Одну главу два раздела держат по-разному, и счёт по главе это прячет.

    Глава 25 у `1c-extensions` разобрана (§25.3.10 — удаление расширения
    стирает историю), а у `1c-metadata-objects` нет. Пока строка карты
    называла оба раздела вместе, расхождение было невидимо.
    """
    таблица = ТАБЛИЦА.replace(
        "| 30 Расширения | `1c-extensions` | целиком |",
        "| 25 История данных | `1c-extensions` | целиком |")
    monkeypatch.setattr(мод, "следы",
                        lambda глава, навык: 2 if навык == "1c-extensions" else 0)
    находки = мод.проверить(мод.строки_карты(таблица))
    пустые = [(г, н) for в, г, н, *_ in находки if в == "пустое обещание"]
    assert ("25", "1c-extensions") not in пустые
    assert ("25", "1c-metadata-objects") not in пустые, (
        "у метаданных обещание честное — «ничего», и ругаться не на что")


def test_шапка_карты_обязана_найтись():
    """Прибор читает разметку чужого файла и обязан падать, а не молчать.

    Ноль находок у прибора, до которого не дошёл вход, выглядит как полное
    благополучие. Набор наелся этой ошибки на приборе полноты.
    """
    import pytest
    with pytest.raises(SystemExit):
        мод.строки_карты("Файл без всякой таблицы карты.\n")


def test_настоящая_карта_набора_сходится_с_содержимым():
    """Приёмка на живом файле: расхождений быть не должно ни одного."""
    находки = мод.проверить(мод.строки_карты())
    assert not находки, "карта разошлась с содержимым: %r" % (находки,)
