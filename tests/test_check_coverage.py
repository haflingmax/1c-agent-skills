"""Проверка прибора полноты: считает ли он рассмотренное, а не только найденное.

Главный дефект этого класса приборов — молчание при пустом входе: «под
вопросом: 0» одинаково выглядит у полного покрытия и у прибора, до которого
вход не дошёл. Поэтому первый же тест здесь — про счётчик входа, а не
про находки.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location(
    "check_coverage", КОРЕНЬ / "tools" / "check-coverage.py")
мод = importlib.util.module_from_spec(спец)
sys.modules["check_coverage"] = мод
спец.loader.exec_module(мод)

# Проба повторяет устройство настоящей выгрузки: заголовок стоит отдельной
# строкой, текст параграфа — следующей. Первая редакция пробы склеивала их
# в одну строку, заголовок захватывал полфразы, и два теста падали не потому,
# что прибор неверен, а потому что вход был выдуман.
ГЛАВА = ("Глава 38. Поставка и поддержка конфигурации", """
38.1. Общая информация
Текст про файлы поставки
38.2.1. Настройка поставки
Правила поставщика и их значения
38.3.4. Обновление конфигурации
Помощник обновления ищет файл
""")


def test_счётчик_считает_вход_а_не_только_находки():
    рассмотрено, дыры = мод.покрытие("пусто", {"38": ГЛАВА}, ["38"])
    assert рассмотрено == 3, "все три подзаголовка обязаны попасть на вход"
    assert len(дыры) == 3


def test_вход_не_дошёл_и_это_видно():
    """Глава без подзаголовков даёт ноль находок — и ноль рассмотренного."""
    рассмотрено, дыры = мод.покрытие("что угодно", {"38": ("Глава 38", "текст")},
                                     ["38"])
    assert рассмотрено == 0 and not дыры, (
        "ноль находок при нулевом входе — это не покрытие, и вызывающий "
        "обязан различать эти два случая по числу рассмотренного")


def test_номер_параграфа_засчитывает_покрытие():
    рассмотрено, дыры = мод.покрытие("правила стоят в §38.2.1 и в §38.3.4, "
                                     "а §38.1 разобран отдельно",
                                     {"38": ГЛАВА}, ["38"])
    assert рассмотрено == 3 and not дыры


def test_пересказ_без_номера_тоже_засчитывается():
    """Иначе дырой объявлялся бы каждый пересказ темы своими словами."""
    навык = ("Настройка поставки описана здесь целиком. "
             "Общая информация про файлы. "
             "Обновление конфигурации идёт помощником.")
    _рассмотрено, дыры = мод.покрытие(навык, {"38": ГЛАВА}, ["38"])
    assert not дыры


def test_склонение_не_делает_тему_дырой():
    навык = "про настройку поставки, общую информацию и обновление конфигурации"
    _рассмотрено, дыры = мод.покрытие(навык, {"38": ГЛАВА}, ["38"])
    assert not дыры, "сравнение по началу слова должно переживать падежи"


def test_чужая_глава_на_вход_не_идёт():
    _рассмотрено, дыры = мод.покрытие("пусто", {"38": ГЛАВА}, ["36"])
    assert not дыры


def test_отбор_по_параграфу_а_не_только_по_главе():
    рассмотрено, _дыры = мод.покрытие("пусто", {"38": ГЛАВА}, ["38.2"])
    assert рассмотрено == 1, "фильтр «38.2» обязан брать 38.2.1 и не брать 38.1"


def test_номер_версии_не_принимается_за_подзаголовок():
    """Завышенный знаменатель опаснее пропуска: он показывает покрытие там,
    где прибор посчитал номер версии за тему источника."""
    глава = ("Глава 38", "Режим совместимости 8.3.10. Версия платформы важна.")
    рассмотрено, _дыры = мод.покрытие("пусто", {"38": глава}, ["8"])
    assert рассмотрено == 0
