"""Проверка переписи отрицаний: находит ли она те, что уже стоили дорого.

Приёмка у этого прибора не «сколько нашёл», а **поймал бы он известные
шесть**. Ложные отрицания `1c-publish-and-operate` разобраны поимённо
в `docs/reviews/2026-09-01-publish-and-operate-refutation.md`; пять из шести
стояли в блоке «Чего … нет» и **не содержали ни одного глагола отрицания**.
Первая редакция прибора искала именно глаголы и находила одно из шести.
Поэтому первый тест здесь — про блок, а не про глагол.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location(
    "check_negations", КОРЕНЬ / "tools" / "check-negations.py")
мод = importlib.util.module_from_spec(спец)
sys.modules["check_negations"] = мод
спец.loader.exec_module(мод)

# Дословные строки из текста раздела ДО правок (коммит 0fb5524). Каждая
# оказалась ложным отрицанием: источник о теме говорит.
ДО_ПРАВОК = """# Версии платформы

Какой-то текст раздела.

## Чего в этих главах нет

- **как остановить автоудаление централизованно** для парка машин;
- **признака того, что обновление дошло до всех машин кластера** — требование
  есть, проверки нет;
- **что делать, если критическая секция прервалась** посередине: обратного
  хода источник не описывает.
"""


def test_блок_чего_нет_даёт_отрицания_без_единого_глагола():
    строки = мод.перепись(ДО_ПРАВОК)
    блочные = [ф for вид, ф in строки if вид == "блок"]
    assert len(блочные) == 3, (
        "все три пункта блока — утверждения об отсутствии, и два из них "
        "не содержат оборота отрицания вовсе")
    assert any("автоудаление" in ф for ф in блочные)
    assert any("критическая секция" in ф for ф in блочные)


def test_многострочный_пункт_собирается_в_одну_строку():
    строки = мод.перепись(ДО_ПРАВОК)
    длинный = [ф for вид, ф in строки
               if вид == "блок" and "обновление дошло" in ф][0]
    assert "проверки нет" in длинный, (
        "пункт продолжается на второй строке; разорванный пополам, он "
        "потерял бы вторую половину утверждения")


def test_блок_кончается_на_следующем_заголовке():
    текст = ДО_ПРАВОК + "\n## Следующий раздел\n\n- обычный пункт, не отрицание\n"
    блочные = [ф for вид, ф in мод.перепись(текст) if вид == "блок"]
    assert len(блочные) == 3 and not any("обычный пункт" in ф for ф in блочные)


def test_отрицание_в_ёлочках_принадлежит_источнику():
    текст = "Источник прямо пишет: «данный режим не поддерживается» — и точка.\n"
    проза = [ф for вид, ф in мод.перепись(текст) if вид == "проза"]
    assert not проза, (
        "отрицание внутри цитаты сказал источник; его верность стережёт "
        "check-quotes.py, и переписывать его как утверждение набора нельзя")


def test_указание_не_считается_утверждением_об_отсутствии():
    текст = "Так делать не рекомендуется, и не следует полагаться на умолчание.\n"
    assert not мод.перепись(текст), (
        "«не рекомендуется» — совет, а не утверждение о содержимом источника")


def test_проза_с_оборотом_отрицания_попадает_в_перепись():
    текст = "Признака сработавшего параметра источник не называет.\n"
    виды = [вид for вид, _ in мод.перепись(текст)]
    assert виды == ["проза"]


def test_счётчик_запроса_не_отдаёт_служебных_слов():
    слова = мод.запрос("**как остановить автоудаление централизованно** "
                       "для парка машин, потому что источник не описывает")
    assert "автоудаление" in слова
    assert not any(с.lower() in ("источник", "описывает") for с in слова), (
        "служебные слова набора запросом к корпусу быть не могут")


def test_пустой_вход_виден_по_числам_а_не_по_нулю_находок():
    """Ноль отрицаний у пустого файла и у безупречного навыка выглядит
    одинаково; различает их только число прочитанных файлов, и оно
    печатается отчётом."""
    assert мод.перепись("") == []


# --- заголовок блока: «нет» в нём стоит не всегда -------------------------

def test_блок_узнаётся_и_без_слова_нет():
    """«Чего эти стандарты не покрывают» — такой же блок отсутствий.

    Первая редакция образца требовала слова «нет», и два блока набора
    из тридцати одного были прибору не видны. Невидимый блок не проверит
    никто — ровно то, ради чего прибор написан.
    """
    формы = [
        "## Чего в главе 22 нет",
        "## Чего здесь нет",
        "## Чего эти стандарты не покрывают",
        "## Чего система стандартов о расширениях не говорит",
        "## Чего в стандарте 453 не описывается",
    ]
    for заголовок in формы:
        текст = заголовок + "\n\n- пункт про отсутствие;\n"
        виды = [в for в, _ in мод.перепись(текст)]
        assert виды == ["блок"], "не узнан заголовок: %s" % заголовок


def test_обычный_заголовок_блоком_не_считается():
    текст = "## Чего мы добились\n\n- обычный пункт, не отрицание\n"
    assert not [в for в, _ in мод.перепись(текст) if в == "блок"]
