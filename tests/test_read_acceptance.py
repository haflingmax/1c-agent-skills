"""Читатель журналов приёмки: считает ли он то, что обещает.

Главное число этапа ИСПЫТАНИЯ — «без поднятого раздела ссылок на источник
не бывает вовсе» — считает именно этот прибор. Числу можно верить ровно
настолько, насколько проверен счётчик, и один раз он уже занижал: узкая
редакция образца не ловила форму «стандарт 1С № 686».
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location(
    "read_acceptance", КОРЕНЬ / "tools" / "read-acceptance.py")
мод = importlib.util.module_from_spec(спец)
sys.modules["read_acceptance"] = мод
спец.loader.exec_module(мод)


def test_считаются_все_формы_ссылки_включая_ту_что_прибор_упускал():
    """«Стандарт 1С № 686» — форма из живого ответа прогона 4.

    Узкая редакция образца её не ловила, и прибор занижал главное число
    этапа. Форма закреплена тестом, чтобы сужение образца падало здесь.
    """
    текст = ("Стандарт 540, пункт 5 запрещает; см. также std669 "
             "и стандарт 1С № 686, а механика — в §32.1.")
    assert мод.ссылки(текст) == 4, (
        "три номера стандарта в разных формах и один адрес параграфа")


def test_повтор_одной_ссылки_считается_один_раз():
    assert мод.ссылки("std686 и ещё раз std686, стандарт 686") == 1


def test_число_без_слова_стандарт_ссылкой_не_считается():
    """«Ошибка 504», «строка 500», «1,523 секунды» — не стандарты.

    На свободном поиске числа набор уже попадался при сверке стандартов
    по всему набору; здесь тот же образец сужен заранее.
    """
    текст = "Вернулась ошибка 504, в строке 500, за 1,523 секунды."
    assert мод.ссылки(текст) == 0


def test_у_сорвавшегося_прогона_ссылок_ноль_а_не_ошибка():
    assert мод.ссылки(мод.СБОЙ + " Invalid prompt") == 0
    assert мод.ссылки("") == 0
    assert мод.ссылки(None) == 0


def test_адрес_параграфа_узнаётся_с_пробелом_и_без():
    assert мод.ссылки("см. §5.14.2.4 и § 30.4") == 2


def test_в_исходнике_прибора_нет_управляющих_символов():
    """Регулярное выражение этого файла один раз уже пришло искажённым.

    Строку с `\\b` протащили через heredoc, и в файл попал настоящий символ
    забоя (0x08): образец перестал требовать границу слова, а на глаз
    и в выводе `Read` разницы не видно. Счётчик при этом молча занизил
    результат втрое — 3 прогона со ссылками вместо 14.

    Проверка дешёвая и ловит весь класс: в исходнике не должно быть
    управляющих символов, кроме перевода строки и табуляции.
    """
    найдено = {}
    for файл in sorted((КОРЕНЬ / "tools").glob("*.py")):
        исходник = файл.read_text(encoding="utf-8")
        плохие = sorted({с for с in исходник if ord(с) < 32 and с not in "\n\t"})
        if плохие:
            найдено[файл.name] = [hex(ord(с)) for с in плохие]
    assert not найдено, "управляющие символы в исходниках: %r" % найдено
