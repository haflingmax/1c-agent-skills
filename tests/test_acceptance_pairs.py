"""Приёмочные пары против каталога навыков: не остался ли раздел без пары.

Пара-антипод — единственная проверка набора, которую нельзя сделать чтением.
Она спрашивает не «написано ли правило», а **срабатывает ли оно**: Neg берётся
из блока «Что здесь необратимо» самого раздела, и если агент это правило
не поднимает, значит оно написано так, что не работает.

Раздел без пары такой проверки не проходит никогда, и заметить это чтением
невозможно — файл `run-acceptance.ps1` длинный, а отсутствие строки в нём
не бросается в глаза. До 05.09.2026 без пары стояли тринадцать разделов
из шестнадцати.

Тест сверяет каталог `skills/` со списком пар. Он не запускает агентов
и ничего не измеряет: его вопрос — есть ли пара вообще.
"""
import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
СКРИПТ = КОРЕНЬ / "tools" / "run-acceptance.ps1"
НАВЫКИ = КОРЕНЬ / "skills"

# Пар меньше числа разделов быть не может; проверка на случай, если разбор
# разметки скрипта развалится молча. Ноль находок у прибора, до которого
# не дошёл вход, выглядит как полное благополучие.
МИНИМУМ_ПАР = 16


def пары():
    """[(id, имена разделов)] из объявления $pairs в скрипте приёмки."""
    текст = io.open(СКРИПТ, encoding="utf-8-sig").read()
    ids = re.findall(r"^\s*Id = (\d+)$", текст, re.M)
    строки = re.findall(r"^\s*Skill = '([^']+)'$", текст, re.M)
    assert len(ids) == len(строки), (
        "у каждой пары обязаны быть и Id, и Skill: %d против %d"
        % (len(ids), len(строки)))
    return [(int(i), re.findall(r"[a-z0-9-]{4,}", с))
            for i, с in zip(ids, строки)]


def навыки_на_диске():
    return sorted(п.name for п in НАВЫКИ.iterdir()
                  if п.is_dir() and (п / "SKILL.md").is_file())


def test_разметка_скрипта_приёмки_разбирается():
    найдено = пары()
    assert len(найдено) >= МИНИМУМ_ПАР, (
        "в run-acceptance.ps1 разобрано пар: %d. Либо разметка изменилась, "
        "либо пары пропали — и то и другое чинится, а не игнорируется"
        % len(найдено))


def test_у_каждого_раздела_есть_хотя_бы_одна_пара():
    названы = set()
    for _id, имена in пары():
        названы.update(имена)
    без_пары = [н for н in навыки_на_диске() if н not in названы]
    assert not без_пары, (
        "разделы без приёмочной пары: %s. Пара — единственная проверка, "
        "которая спрашивает, срабатывает ли правило, а не написано ли оно"
        % ", ".join(без_пары))


def test_имена_разделов_в_парах_существуют_на_диске():
    """Пара, ссылающаяся на несуществующий раздел, — та же переадресация
    в пустоту, что набор ловит в своих текстах."""
    на_диске = set(навыки_на_диске())
    чужие = sorted({н for _id, имена in пары() for н in имена
                    if н not in на_диске})
    assert not чужие, "в парах названы несуществующие разделы: %s" % ", ".join(чужие)


def test_номера_пар_не_повторяются():
    """Отбор идёт по -PairIds, и повтор номера тихо гонял бы одно вместо
    другого."""
    номера = [i for i, _ in пары()]
    assert len(номера) == len(set(номера)), "повторяющиеся Id: %r" % номера


def test_у_каждой_пары_есть_обе_полярности_и_обе_приёмки():
    текст = io.open(СКРИПТ, encoding="utf-8-sig").read()
    for поле in ("PosPrompt", "NegPrompt", "ExpectPos", "ExpectNeg"):
        сколько = len(re.findall(r"^\s*%s = '" % поле, текст, re.M))
        assert сколько == len(пары()), (
            "поле %s объявлено %d раз при %d парах — пара без ожидания "
            "проверяется на глаз, то есть не проверяется"
            % (поле, сколько, len(пары())))
