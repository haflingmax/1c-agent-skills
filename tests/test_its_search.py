@needs_its
def test_section_name_that_prefixes_a_legacy_branch():
    """Точное имя не должно захватывать устаревшую ветку.

    «Разработка пользовательских интерфейсов» — начало имени
    «Разработка пользовательских интерфейсов (обычное приложение)»,
    и поиск вхождением возвращал 62 стандарта вместо 33, подмешивая
    29 из ветки, сознательно вне охвата набора. Раздутый список при этом
    выглядел бы подтверждённым — поймал агент сверки, а не тест: он
    проверял только имена без коллизий.
    """
    свои = mod.раздел("Разработка пользовательских интерфейсов")
    чужие = mod.раздел("Разработка пользовательских интерфейсов (обычное приложение)")
    assert len(свои) == 33
    assert len(чужие) == 29
    свои_ид = {str(x["id"]) for x in свои}
    чужие_ид = {str(x["id"]) for x in чужие}
    assert not (свои_ид & чужие_ид), "ветки пересеклись"


