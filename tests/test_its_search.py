@needs_its
def test_service_document_is_marked_and_not_counted_in_sections():
    """std788 — журнал изменений системы стандартов, а не стандарт.

    Он приходит из оглавления 319-м и ни в одном разделе не значится;
    в корпусе помечен служебным, чтобы не попал в счёт по разделам.
    """
    корпус = json.loads((ITS / "v8std-full.json").read_text(encoding="utf-8"))
    служебные = [x for x in корпус["статьи"] if x.get("служебная")]
    assert len(служебные) == 1
    assert str(служебные[0]["id"]) == "788"
    assert корпус["статей"] == 319
    в_разделах = set()
    for имя in mod.имена_разделов():
        в_разделах |= {str(x["id"]) for x in mod.раздел(имя)}
    assert "788" not in в_разделах
    assert len(в_разделах) == 318


# --- Фраза из собственного вывода должна находиться этим же инструментом ---
#
# Поиск идёт по СЫРОМУ тексту корпуса, где переносы строк стоят внутри фраз,
# а выдержка печатается склеенной через re.sub(r"\s+", " ", ...). Из-за этого
# фраза, скопированная посимвольно из вывода, инструментом не находилась —
# и выглядело это как «темы в документации нет». Три агента выписки нашли
# дефект независимо, каждый решив сперва, что ошибся сам.


def test_пробел_в_запросе_переживает_перенос_строки():
    образец = mod.образец("Конфигурация ‑ Проверка конфигурации")
    сырое = "выбрать пункт Конфигурация ‑\nПроверка конфигурации. На экран"
    assert re.search(образец, сырое, re.IGNORECASE), (
        "фраза с переносом внутри обязана находиться: иначе вывод инструмента "
        "нельзя использовать как вход для него же")


def test_обычный_дефис_находит_неразрывное_тире():
    """Рабочее тире портала ИТС — U+2011, а не то, что набирают с клавиатуры."""
    образец = mod.образец("Конфигурация - Проверка")
    assert re.search(образец, "пункт Конфигурация ‑ Проверка", re.IGNORECASE)
    assert re.search(образец, "пункт Конфигурация — Проверка", re.IGNORECASE)
    assert re.search(образец, "пункт Конфигурация – Проверка", re.IGNORECASE)


def test_ё_по_прежнему_не_отличается_от_е():
    образец = mod.образец("все объекты")
    assert re.search(образец, "всё объекты", re.IGNORECASE)


def test_спецзнаки_запроса_не_толкуются_как_регулярка():
    """Запрос — фраза, а не образец: точка не должна означать «любой знак»."""
    образец = mod.образец("а.б")
    assert re.search(образец, "а.б")
    assert not re.search(образец, "аХб")
