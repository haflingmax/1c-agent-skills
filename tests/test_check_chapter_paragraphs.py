"""Проверка переписи параграфов глав без адреса в наборе.

Приёмка именная. Карта 06.09.2026 писала про главу 9 «прочитана почти
целиком, не взят один параграф», а без единого адреса оставалось около
28 тыс. знаков — пессимистическая блокировка, таблицы режимов по СУБД,
умолчание `РежимБлокировок` у `НачатьТранзакцию()`. Прибор карты этого
не видел: ему хватало одного следа главы в разделе.
"""
import importlib.util
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
спец = importlib.util.spec_from_file_location(
    "check_chapter_paragraphs", КОРЕНЬ / "tools" / "check-chapter-paragraphs.py")
мод = importlib.util.module_from_spec(спец)
sys.modules["check_chapter_paragraphs"] = мод
спец.loader.exec_module(мод)

ГЛАВА = (
    "Глава 9. Работа с данными 9.1. Механизм транзакций 9.1.1. Общие "
    "сведения Текст про транзакции. 9.1.2. Явный вызов Ещё текст. "
    "9.2. Блокировки 9.2.1. Пессимистическая блокировка Длинный текст "
    "про блокировку формы. 9.2.2. Управляемые блокировки Таблица по СУБД. "
    "9.3. Индексы Текст про индексы.")


def test_листьями_считаются_только_параграфы_без_детей():
    номера = [н for н, _р, _з in мод.листья(ГЛАВА, "9")]
    assert номера == ["9.1.1", "9.1.2", "9.2.1", "9.2.2", "9.3"], (
        "9.1 и 9.2 — родители: их текст до первого ребёнка — вступление, "
        "а считать надо листья")


def test_адрес_подраздела_покрывает_лист_а_соседний_номер_нет():
    адреса = {"9.2.1.3", "9.1.20"}
    без = [н for н, _р, _з in мод.без_адреса(мод.листья(ГЛАВА, "9"), адреса)]
    assert "9.2.1" not in без, "адрес §9.2.1.3 — внутри листа 9.2.1"
    assert "9.1.2" in без, "§9.1.20 — другой параграф, а не часть 9.1.2"


def test_диапазон_и_перечень_адресов_раскрываются_по_концам():
    адреса = мод.адреса(["разбор (§9.1.1–9.1.2, 9.3) и ещё §9.2.2"])
    assert {"9.1.1", "9.1.2", "9.3", "9.2.2"} <= адреса, (
        "набор пишет «§9.1.2–9.1.4, 9.2.2.3»; знак параграфа стоит только "
        "у первого адреса, остальные иначе пропадут")


def test_точка_конца_предложения_не_портит_адрес():
    assert "9.4.1" in мод.адреса(["как сказано в §9.4.1."])


def test_карта_в_счёт_не_идёт(tmp_path, monkeypatch):
    """Адрес в строке карты «не взяты (§9.2.3.7.4)» — не разбор."""
    карта = tmp_path / "developing-1c-configurations" / "references" / "architecture.md"
    карта.parent.mkdir(parents=True)
    карта.write_text("Не взяты примеры (§9.2.3.7.4)", encoding="utf-8")
    справка = tmp_path / "1c-queries" / "references" / "data.md"
    справка.parent.mkdir(parents=True)
    справка.write_text("разбор §9.1.2", encoding="utf-8")
    monkeypatch.setattr(мод, "НАВЫКИ", tmp_path)
    monkeypatch.setattr(мод, "КАРТА", карта)
    тексты = мод.тексты_набора()
    assert len(тексты) == 1 and "§9.1.2" in тексты[0]


def test_глава_которой_нет_в_корпусе_роняет_прибор(monkeypatch):
    """Ноль находок у прибора, до которого не дошёл вход, — это не благополучие."""
    monkeypatch.setattr(мод, "главы_руководства", lambda: {})
    assert мод.main(["99"]) == 2
